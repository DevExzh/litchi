#!/usr/bin/env python3
"""Record 0340 linear-scaling check over the batch-closure runs (record 0337's script, retitled).

For each (format, owner, scenario, fixture) measured at 100, 1,000 and
10,000 operations on one fixture, the marginal cost per operation of each
leg is (t(1k) - t(100)) / 900 and (t(10k) - t(1k)) / 9000 (medians over
the trials' medians). A leg scales linearly in operation count when the
second marginal is within 1.5x of the first ("growth"). The leaf's own
shape (a leaf whose per-operation cost grows with the document, or whose
bound splits 10,000 operations into three commits) shows in both legs, so
the verdict is on the unified layer's added cost per operation, unified
marginal minus leaf marginal: linear when the 1k→10k value is within 1.5x
of the 100→1k value, or below 0.5 µs (timer and noise level at these
sizes). Writes scaling.md next to this script.
"""

import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    groups = {}
    for path in sorted((HERE / "abba").glob("batch-*.json")):
        tag = path.name.split("-")[2]
        for c in json.loads(path.read_text())["cases"]:
            key = (tag, c["format"], c["owner"], c["scenario"], c["fixture_targets"])
            groups.setdefault(key, {}).setdefault(c["operations"], []).append(c)
    lines = [
        "# Record 0340 linear-scaling check",
        "",
        "Generated by `scaling.py` from `abba/batch-*.json`. µs are medians of the trials' medians; "
        "marginal = added cost per added operation between two counts on the same fixture; "
        "growth = marginal(1k→10k) / marginal(100→1k); added = unified marginal − leaf marginal "
        "(the unified layer's own cost per operation); linear when added(1k→10k) ≤ max(1.5 × added(100→1k), 0.5 µs).",
        "",
        "| run | format | owner | scenario | fixture | unified µs 100 / 1k / 10k | unified marginal µs/op | "
        "unified growth | leaf marginal µs/op | leaf growth | added µs/op | linear (added cost) |",
        "|---|---|---|---|---:|---|---|---:|---|---:|---|---|",
    ]
    for (tag, fmt, owner, scen, fixture), by_n in sorted(groups.items()):
        if not all(n in by_n for n in (100, 1000, 10000)):
            continue
        med = lambda n, leg: statistics.median(c[f"{leg}_median_ns"] for c in by_n[n]) / 1000

        def marg(leg):
            a = (med(1000, leg) - med(100, leg)) / 900
            b = (med(10000, leg) - med(1000, leg)) / 9000
            return a, b, (b / a if a > 0 else float("inf"))

        ua, ub, ug = marg("unified")
        la, lb, lg = marg("leaf")
        aa, ab = ua - la, ub - lb
        linear = ab <= max(1.5 * aa, 0.5)
        lines.append(
            f"| {tag} | {fmt} | {owner} | {scen} | {fixture:,} | "
            f"{med(100, 'unified'):,.0f} / {med(1000, 'unified'):,.0f} / {med(10000, 'unified'):,.0f} | "
            f"{ua:.3f} → {ub:.3f} | {ug:.2f} | {la:.3f} → {lb:.3f} | {lg:.2f} | "
            f"{aa:.3f} → {ab:.3f} | {'yes' if linear else '**no**'} |"
        )
    (HERE / "scaling.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
