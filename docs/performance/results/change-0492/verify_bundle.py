#!/usr/bin/env python3
"""Seal the 0492 bundle and recompute its source-bound comparison evidence."""
import json
from pathlib import Path
import sys

import measure
from support import ROOT, TEMP, TARGET_DIR, meta, read, write


def inventory():
    result = {}
    for path in sorted(ROOT.rglob('*')):
        if path.is_symlink():
            raise RuntimeError(f'symlink in evidence: {path}')
        if path.is_file() and path != ROOT / 'seal.json':
            if '__pycache__' in path.parts or path.suffix == '.pyc':
                raise RuntimeError(f'generated bytecode in evidence: {path}')
            result[path.relative_to(ROOT).as_posix()] = meta(path)
    return result


def verify_evidence():
    builds = measure.load_builds()
    protocol, protocol_hash = measure._load_protocol()
    measure.require(protocol == measure.protocol_value(builds), 'protocol/build mismatch')
    for attempt, pilot in [('pilot2', True), ('formal1', False)]:
        entries = measure._collect(attempt, builds, protocol, protocol_hash, pilot=pilot)
        summary = measure.analyze_data(entries, builds, pilot=pilot)
        suffix = '-pilot' if pilot else ''
        measure.require(summary == read(ROOT / 'analysis' / f'{attempt}{suffix}.json'),
                        f'{attempt} analysis does not recompute')
        verification = read(ROOT / 'verification' / f'{attempt}{suffix}.json')
        measure.require(verification['status'] == 'pass' and
                        verification['protocol_sha256'] == protocol_hash and
                        verification['summary_sha256'] == meta(ROOT / 'analysis' / f'{attempt}{suffix}.json')['sha256'],
                        f'{attempt} verification binding failed')
    review = read(ROOT / 'results-review.json')
    measure.require(review['schema'] == 'docx-read-ahead-results-review-v1' and
                    review['version'] == 1 and review['attempt'] == 'formal1' and
                    review['formal_processes'] == 16 and review['measured_samples'] == 480,
                    'allocation review inventory differs')
    measure.require(review['protocol_sha256'] == protocol_hash and
                    review['source'] == builds['normal']['source'], 'allocation review custody differs')
    expected_comparisons = []
    for pair in summary['comparisons']:
        item = {key: pair[key] for key in ('role', 'repeat', 'baseline_arm', 'candidate_arm')}
        item['delay'] = 'delayed' if '1000us' in pair['baseline_arm'] else 'zero'
        for side in ('baseline', 'candidate'):
            label = f"r{pair['repeat']}-{pair['role']}-{pair[side + '_arm']}"
            path = ROOT / 'captures' / 'formal1' / label / 'report.json'
            rows = read(path)['rows']
            value = {'label': label, 'report_sha256': meta(path)['sha256']}
            for field in ('allocation_calls', 'reallocation_calls'):
                if pair['role'] == 'normal':
                    value[field] = None
                else:
                    counts = [row['allocation'][field] for row in rows]
                    measure.require(len(set(counts)) == 1, 'allocation review constant-count assumption differs')
                    value[field] = {'all': counts[0], 'count': len(counts)}
            item[side] = value
        expected_comparisons.append(item)
    measure.require(review['comparisons'] == expected_comparisons, 'allocation review does not recompute')
    gate_contract = read(ROOT / 'final-gates.json')
    required = gate_contract['gates']
    measure.require(len(required) >= 9 and len(required) == len(set(required)), 'gate inventory invalid')
    for label in required:
        path = ROOT / 'validation' / f'{label}.json'
        binding = measure._gate_binding({'path': str(path), 'sha256': meta(path)['sha256']}, path)
        measure.require(binding['source'] == builds['normal']['source'], f'{label}: gate source differs')
        measure.require(binding['argv'] == gate_contract['commands'][label], f'{label}: gate command differs')
    tested = read(ROOT / 'python2-test-custody.json')
    measure.require(tested['gate'] == meta(ROOT / 'validation/python2.json'), 'Python test receipt changed')
    measure.require(tested['helpers'] == {name: meta(ROOT / name) for name in measure.DRIVER_FILES},
                    'tested Python helpers changed')
    cleanup = read(ROOT / 'cleanup.json')
    measure.require(cleanup['status'] == 'pass' and cleanup['target'] == str(TARGET_DIR), 'cleanup missing')
    measure.require(not TARGET_DIR.exists(), 'disposable build target remains')
    for role, build in builds.items():
        binary = Path(build['binary']['path'])
        name = 'litchi-perf-baseline' + ('-alloc' if role == 'allocator' else '')
        measure.require(binary == TEMP / 'final2' / role / name, 'retained executable escaped owned path')
        measure.require(cleanup['retained'][role] == {'path': str(binary), **meta(binary)}, 'retained binary changed')
    actual_files = sorted(str(p) for p in TEMP.rglob('*') if p.is_file())
    expected_files = sorted(build['binary']['path'] for build in builds.values())
    measure.require(actual_files == expected_files, 'unexpected temporary files remain')
    expected_dirs = sorted(str(path) for path in [TEMP / 'final2', TEMP / 'final2' / 'normal',
                                                TEMP / 'final2' / 'allocator'])
    actual_dirs = sorted(str(path) for path in TEMP.rglob('*') if path.is_dir())
    measure.require(actual_dirs == expected_dirs, 'unexpected temporary directories remain')
    final_cleanup = read(ROOT / 'final-cleanup.json')
    measure.require(final_cleanup['status'] == 'pass' and final_cleanup['target_absent'] is True,
                    'final cleanup did not pass')
    measure.require(final_cleanup['earlier_cleanup'] == meta(ROOT / 'cleanup.json'),
                    'historical cleanup binding changed')
    measure.require(final_cleanup['temporary_files'] == {str(path): meta(path)
                    for path in map(Path, actual_files)}, 'final retained file inventory changed')
    measure.require(sorted(final_cleanup['temporary_directories']) == actual_dirs,
                    'final retained directory inventory changed')
    return {'status': 'pass', 'formal_samples': 480, 'pilot_samples': 24,
            'required_gates': required, 'protocol_sha256': protocol_hash}


def main():
    if sys.argv[1:] not in [['create'], ['verify']]:
        raise SystemExit('usage: verify_bundle.py create|verify')
    verified = verify_evidence()
    value = {'schema': 'docx-read-ahead-bundle-seal-v1', 'evidence': verified, 'files': inventory()}
    seal = ROOT / 'seal.json'
    if sys.argv[1] == 'create':
        write(seal, value)
    elif read(seal) != value:
        raise RuntimeError('bundle seal differs from recomputed inventory/evidence')
    print(json.dumps({'status': 'pass', 'files': len(value['files']), **meta(seal)}, sort_keys=True))


if __name__ == '__main__':
    main()
