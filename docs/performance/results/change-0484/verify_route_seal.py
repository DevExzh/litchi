#!/usr/bin/env python3
"""Seal artifact integrity and reverify the formal route/axis analysis.

Historical failed diagnostics remain in the inventory. Semantic acceptance
applies to the declared formal measurements and profiles, not every old gate.
"""

import argparse
import json
import os
from pathlib import Path

import analyze_routes as analysis
import metadata_evidence
from common import ROOT, meta, now, read, write


EXCLUDED = {"route-seal.json", "route-seal-verification.json"}


def inventory():
    result = {}
    for path in sorted(ROOT.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"unexpected symlink in evidence bundle: {path}")
        if not path.is_file():
            continue
        relative = path.relative_to(ROOT).as_posix()
        if relative in EXCLUDED:
            continue
        if "__pycache__" in path.parts:
            raise ValueError("remove generated bytecode before sealing")
        result[relative] = meta(path)
    return result


def semantic_check():
    metadata_evidence.check()
    retained = analysis.read_json(ROOT / "route-summary.json")
    actual = analysis.analyze(ROOT / "route-protocol.json", "formal1")
    if actual != retained:
        raise ValueError("formal analysis differs from the retained summary")
    profiles = read(ROOT / "route-profiles" / "profiles1" / "result.json")
    profile_summary = read(ROOT / "route-profiles/profiles1-summary.json")
    if (profile_summary["status"] != "ok" or profile_summary["validation"]["errors"]
            or profile_summary["perf_script_commands"]["pending_count"] != 0):
        raise ValueError("profile postprocessing is incomplete")
    if (profiles["status"] != "ok" or profiles.get("passed") is not True
            or profiles.get("binary_unchanged") is not True
            or profiles.get("failures") != [] or len(profiles["receipts"]) != 24):
        raise ValueError("expected all 24 external profiles to pass")
    cleanup = read(ROOT / "cleanup-replay-dirs-formal1.json")
    execution = read(ROOT / "route-attempts/formal1/execution-inputs.json")
    if cleanup.get("driver_sha256") != meta(ROOT / "cleanup_replay_dirs.py")["sha256"]:
        raise ValueError("cleanup helper binding differs")
    if any(entry["device"] != execution["filesystems"]["evidence"]["device"] for entry in cleanup["entries"]):
        raise ValueError("cleanup filesystem binding differs")
    for item in profiles["receipts"]:
        if item["status"] != "ok":
            raise ValueError("unaccepted external profile")
        record = item["receipt"]
        path = ROOT / record["path"]
        if meta(path) != {key: record[key] for key in ("bytes", "sha256")}:
            raise ValueError(f"profile receipt changed: {path}")
        receipt = read(path)
        if receipt["validation_status"] != "ok":
            raise ValueError(f"profile report validation missing: {path}")
        for relative, artifact in receipt["artifacts"].items():
            if not artifact["present"] or meta(path.parent / relative) != {key: artifact[key] for key in ("bytes", "sha256")}:
                raise ValueError(f"profile artifact changed: {relative}")
    return retained


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("seal", "verify"))
    parser.add_argument("--receipt", action="store_true")
    args = parser.parse_args()
    summary = semantic_check()
    binaries = {role: read(ROOT / "route-attempts" / "formal1" / f"build-{role}.json")["binary"] for role in ("normal", "allocator")}
    for binary in binaries.values():
        path = Path(binary["path"])
        if not path.is_file() or path.is_symlink() or not os.access(path, os.X_OK) or meta(path) != {key: binary[key] for key in ("bytes", "sha256")}:
            raise ValueError(f"copied executable differs: {path}")
    files = inventory()
    path = ROOT / "route-seal.json"
    if args.command == "seal":
        write(path, {"schema": "docx-route-evidence-seal-v1", "sealed_utc": now(),
                     "semantic_scope": "120 route and 108 axis formal processes plus 24 external route profiles and 6 input metadata profiles; historical failed diagnostics retained",
                     "source": summary["source_manifest"], "external_binaries": binaries, "files": files})
    else:
        seal = read(path)
        if seal["schema"] != "docx-route-evidence-seal-v1" or seal["files"] != files or seal["external_binaries"] != binaries or seal["source"] != summary["source_manifest"]:
            raise ValueError("sealed evidence inventory or bindings differ")
    result = {"schema": "docx-route-seal-verification-v1", "status": "pass", "verified_utc": now(),
              "manifest": meta(path), "files": len(files), "formal_processes": 228,
              "formal_samples": 6840, "external_profiles": 30, "analyzer": meta(ROOT / "analyze_routes.py"),
              "verifier": meta(Path(__file__))}
    if args.receipt:
        write(ROOT / "route-seal-verification.json", result)
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
