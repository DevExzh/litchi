#!/usr/bin/env python3
"""Render summary.md for the change 0749 packet: every timing, counter and
allocation table, and every per-round change above +5%.

Usage: summarize.py PACKET > PACKET/summary.md
"""

import json
import os
import statistics
import sys


def load(packet, *parts):
    with open(os.path.join(packet, *parts)) as handle:
        return json.load(handle)


GROUPS = [
    ("CFB-only `OleWriter::write_to` (probe)", lambda n: n.startswith("cfb-write-")),
    ("Common-container control (probe, 0728)", lambda n: n.startswith("container-")),
    ("Public lifecycles (probe, 0728/0734/0745)", lambda n: n.startswith(("ppt-remove", "doc-replace"))),
    ("Harness edit/save selectors", lambda n: n.endswith(("one_edit_save/tiny", "one_edit_save/large"))),
    ("Controls that should not change", lambda n: n in ("ppt-noop-45543", "cfb-open-read-45543") or n.startswith(("cfb_open", "cfb_read_one")) or "noop_edit_save" in n),
]


def us(value):
    return f"{value / 1000:,.1f}"


def main():
    packet = sys.argv[1]
    analysis = load(packet, "matrix", "analysis.json")
    cases = analysis["cases"]
    out = []
    out.append("# 0749 summary tables\n")
    out.append("Generated by `scripts/summarize.py` from `matrix/analysis.json`, the counter lanes and the allocation lane. "
               "Timings: median of per-process p50s per arm (µs), and the median over paired rounds of the per-round change "
               "cand/base − 1 with its 95% percentile-bootstrap interval (10,000 resamples, seed 749). Every probe output digest "
               f"is identical across all processes of both arms: `{analysis['all_probe_outputs_identical_across_arms']}`.\n")
    for title, match in GROUPS:
        out.append(f"## {title}\n")
        out.append("| Case | Rounds | Base p50 µs | Cand p50 µs | Δ p50 (median) | 95% CI | Δ mean | Δ p95 |")
        out.append("|---|---:|---:|---:|---:|---|---:|---:|")
        for name, case in cases.items():
            if not match(name):
                continue
            arms = case["arms"]
            change = case["median_paired_change_pct"]
            interval = case["bootstrap95_median_paired_change_pct"]["p50"]
            out.append(f"| `{name}` | {case['paired_rounds']} | {us(arms['base']['median_process_p50_ns'])} | "
                       f"{us(arms['cand']['median_process_p50_ns'])} | {change['p50']:+.2f}% | "
                       f"[{interval[0]:+.2f}%, {interval[1]:+.2f}%] | {change['mean']:+.2f}% | {change['p95']:+.2f}% |")
        out.append("")

    out.append("## Every per-round change above +5%\n")
    out.append("| Case | Round (argv[0] +8·r bytes) | Metric | Base µs | Cand µs | Change |")
    out.append("|---|---:|---|---:|---:|---:|")
    for flag in sorted(analysis["flags_above_plus_5_pct"], key=lambda f: (f["case"], f["round"], f["metric"])):
        out.append(f"| `{flag['case']}` | {flag['round']} | {flag['metric']} | {us(flag['base_ns'])} | {us(flag['cand_ns'])} | {flag['change_pct']:+.2f}% |")
    out.append(f"\n{len(analysis['flags_above_plus_5_pct'])} flags.\n")

    tuned = load(packet, "tuned", "analysis.json")
    out.append("## Timing check under fixed glibc malloc thresholds\n")
    out.append("`GLIBC_TUNABLES=glibc.malloc.trim_threshold=268435456:glibc.malloc.mmap_threshold=268435456`, "
               "8 rounds, same method. Output digests identical across arms: "
               f"`{tuned['all_probe_outputs_identical_across_arms']}`.\n")
    out.append("| Case | Rounds | Base p50 µs | Cand p50 µs | Δ p50 (median) | 95% CI | Δ mean | Δ p95 |")
    out.append("|---|---:|---:|---:|---:|---|---:|---:|")
    for name, case in tuned["cases"].items():
        arms = case["arms"]
        change = case["median_paired_change_pct"]
        interval = case["bootstrap95_median_paired_change_pct"]["p50"]
        out.append(f"| `{name}` | {case['paired_rounds']} | {us(arms['base']['median_process_p50_ns'])} | "
                   f"{us(arms['cand']['median_process_p50_ns'])} | {change['p50']:+.2f}% | "
                   f"[{interval[0]:+.2f}%, {interval[1]:+.2f}%] | {change['mean']:+.2f}% | {change['p95']:+.2f}% |")
    out.append("\nEvery per-round change above +5% under fixed thresholds:\n")
    out.append("| Case | Round | Metric | Base µs | Cand µs | Change |")
    out.append("|---|---:|---|---:|---:|---:|")
    for flag in sorted(tuned["flags_above_plus_5_pct"], key=lambda f: (f["case"], f["round"], f["metric"])):
        out.append(f"| `{flag['case']}` | {flag['round']} | {flag['metric']} | {us(flag['base_ns'])} | {us(flag['cand_ns'])} | {flag['change_pct']:+.2f}% |")
    out.append(f"\n{len(tuned['flags_above_plus_5_pct'])} flags.\n")

    counters = load(packet, "counters", "per-owner.json")
    out.append("## Per-owner counters (median of three argv[0] layouts)\n")
    out.append("Probe processes ran with `--oracle first`. `instructions:u` and `cycles` are per timed owner; harness rows include the harness's own per-sample oracle work.\n")
    out.append("| Case | instructions:u base | cand | Δ | cycles base | cand | Δ | cycles per layout, base / cand (k) |")
    out.append("|---|---:|---:|---:|---:|---:|---:|---|")
    for name, events in counters["summary"].items():
        ib = statistics.median(events["instructions:u"]["base"])
        ic = statistics.median(events["instructions:u"]["cand"])
        cb = statistics.median(events["cycles"]["base"])
        cc = statistics.median(events["cycles"]["cand"])
        layouts = "{} / {}".format([round(v / 1000) for v in events["cycles"]["base"]],
                                   [round(v / 1000) for v in events["cycles"]["cand"]])
        out.append(f"| `{name}` | {ib:,.0f} | {ic:,.0f} | {events['instructions:u']['median_change_pct']:+.2f}% | "
                   f"{cb:,.0f} | {cc:,.0f} | {events['cycles']['median_change_pct']:+.2f}% | {layouts} |")
    out.append("")

    read = load(packet, "counters", "read-controls.json")
    out.append("## Harness read controls, per-owner counters\n")
    out.append("| Case | instructions:u Δ | instructions Δ | cycles Δ | cycles per layout, base / cand (k) |")
    out.append("|---|---:|---:|---:|---|")
    for name, events in read["summary"].items():
        layouts = "{} / {}".format([round(v / 1000) for v in events["cycles"]["base"]],
                                   [round(v / 1000) for v in events["cycles"]["cand"]])
        out.append(f"| `{name}` | {events['instructions:u']['median_change_pct']:+.3f}% | "
                   f"{events['instructions']['median_change_pct']:+.3f}% | {events['cycles']['median_change_pct']:+.2f}% | {layouts} |")
    out.append("")

    out.append("## `doc_semantic_one_edit_save` page faults per owner across ten argv[0] layouts\n")
    for label, file in (("default glibc malloc", "page-fault-layouts.json"),
                        ("`glibc.malloc.trim_threshold` and `mmap_threshold` = 256 MiB", "page-fault-layouts-glibc-tuned.json")):
        data = load(packet, "counters", file)
        out.append(f"**{label}**\n")
        out.append("| Case | Arm | page faults per owner (layouts 0..9) | cycles per owner, k (median) | instructions:u, k (median) |")
        out.append("|---|---|---|---:|---:|")
        for name, arms in data["summary"].items():
            for arm in ("base", "cand"):
                events = arms[arm]
                out.append(f"| `{name}` | {arm} | {[round(v) for v in events['page-faults']]} | "
                           f"{statistics.median(events['cycles']) / 1000:,.0f} | {statistics.median(events['instructions:u']) / 1000:,.0f} |")
        out.append("")

    allocation = load(packet, "allocation", "allocation.json")
    out.append("## Allocation per owner (counting allocator, 5 owners per process)\n")
    out.append("| Case | Bytes base | Bytes cand | Δ bytes | Calls base | Calls cand | Δ calls | Peak live base | Peak live cand |")
    out.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for name, arms in allocation["summary"].items():
        base, cand = arms["base"]["per_owner"], arms["cand"]["per_owner"]
        out.append(f"| `{name}` | {base['allocated_bytes']:,} | {cand['allocated_bytes']:,} | "
                   f"{cand['allocated_bytes'] - base['allocated_bytes']:+,} | {base['allocation_calls']:,} | "
                   f"{cand['allocation_calls']:,} | {cand['allocation_calls'] - base['allocation_calls']:+,} | "
                   f"{base['peak_live_bytes']:,} | {cand['peak_live_bytes']:,} |")
    identical = all(arms[arm]["owners_identical"] for arms in allocation["summary"].values() for arm in ("base", "cand"))
    same_output = all(arms["base"]["output_sha256"] == arms["cand"]["output_sha256"] for arms in allocation["summary"].values())
    out.append(f"\nEvery owner of every allocation process is identical: `{identical}`. Base and candidate outputs identical: `{same_output}`.\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
