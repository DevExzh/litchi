#!/usr/bin/env python3
"""Verify retained 0490 formal/profile evidence and its complete file inventory."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
from datetime import datetime, timezone

sys.dont_write_bytecode = True
import sync_profiles
import variance

ROOT = Path(__file__).resolve().parent
EXCLUDED = {'seal.json', 'seal-verification.json'}


def meta(path):
    with path.open('rb') as stream:
        return {'bytes': path.stat().st_size, 'sha256': hashlib.file_digest(stream, 'sha256').hexdigest()}


def write(path, value):
    with path.open('x') as stream:
        json.dump(value, stream, indent=2, sort_keys=True, allow_nan=False)
        stream.write('\n')


def inventory():
    result = {}
    for path in sorted(ROOT.rglob('*')):
        if path.is_symlink():
            raise ValueError(f'symlink in evidence: {path}')
        if '__pycache__' in path.parts or path.suffix in {'.pyc', '.pyo'}:
            raise ValueError(f'generated bytecode in evidence: {path}')
        if path.is_dir():
            continue
        if not path.is_file():
            raise ValueError(f'non-regular evidence: {path}')
        relative = path.relative_to(ROOT).as_posix()
        if relative not in EXCLUDED:
            result[relative] = meta(path)
    return result


def validate():
    variance.verify(ROOT / 'variance-summary.json')
    formal = variance.read_json(ROOT / 'variance-summary.json')
    if formal['inventory']['processes'] != 72 or formal['inventory']['samples'] != 4320 or not formal['identity']['all_rows_exact']:
        raise ValueError('formal inventory or content identity incomplete')
    profile = sync_profiles.analyze()
    if profile != sync_profiles.read(ROOT / 'sync-summary.json') or profile['diagnostic_children'] != 8:
        raise ValueError('profile summary differs from raw evidence')
    gate = variance.read_json(ROOT / 'validation/helpers-final.json')
    if gate.get('exit_code') != 0 or type(gate.get('tests')) is not int or gate['tests'] <= 0:
        raise ValueError('final helper test gate incomplete')
    for name, value in gate['helpers'].items():
        if meta(ROOT / name) != value:
            raise ValueError('helper changed since final tests')
    for name, value in gate['artifacts'].items():
        if meta(ROOT / 'validation' / name) != value:
            raise ValueError('test artifact changed')
    output = (ROOT / 'validation/helpers-final.stderr').read_text()
    counts = re.findall(r'^Ran (\d+) tests? in ', output, re.MULTILINE)
    if counts != [str(gate['tests'])] or not output.rstrip().endswith('OK'):
        raise ValueError('test count or successful runner output missing')
    cleanup = variance.read_json(ROOT / 'cleanup.json')
    if cleanup.get('status') != 'pass' or cleanup.get('scratch_files_remaining') != 0 or Path(cleanup['temporary_root']).exists():
        raise ValueError('batch scratch remains or cleanup is incomplete')
    return {'formal_processes': 72, 'formal_samples': 4320, 'paired_blocks': 6,
            'diagnostic_children': 8, 'helper_tests': gate['tests'],
            'content_identity': 'all exact',
            'formal_protocol': formal['protocol'], 'cleanup': meta(ROOT / 'cleanup.json')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['seal', 'verify'], nargs='?', default='verify')
    parser.add_argument('--receipt', action='store_true')
    args = parser.parse_args()
    if args.command == 'seal':
        evidence = validate()
        write(ROOT / 'seal.json', {'schema': 'litchi-file-store-variance-evidence-seal-v1',
                                  'evidence': evidence, 'inventory': inventory()})
        print('Sealed complete 0490 evidence')
        return
    expected = variance.read_json(ROOT / 'seal.json')
    if expected.get('schema') != 'litchi-file-store-variance-evidence-seal-v1' or inventory() != expected.get('inventory'):
        raise ValueError('evidence inventory changed')
    evidence = validate()
    if evidence != expected['evidence']:
        raise ValueError('sealed evidence differs from validators')
    result = {'schema': 'litchi-file-store-variance-seal-verification-v1', 'status': 'pass',
              'files': len(expected['inventory']), **evidence,
              'seal': meta(ROOT / 'seal.json'), 'verified_utc': datetime.now(timezone.utc).isoformat()}
    if args.receipt:
        write(ROOT / 'seal-verification.json', result)
    print(json.dumps(result, sort_keys=True))


if __name__ == '__main__':
    main()
