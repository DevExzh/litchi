#!/usr/bin/env python3
"""Change 0769: render summary.md from the packet's analysis files.

Usage: summarize.py PACKET_DIR > summary.md
"""

import json
import statistics
import sys


def load(path):
    with open(path) as handle:
        return json.load(handle)


def timing_table(analysis, counters):
    rows = [
        "| Case | Base p50 ns | Cand p50 ns | Δ p50 [95% CI] | Δ mean | Δ p95 | Instructions Δ | Cycles Δ |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for case, entry in analysis["cases"].items():
        base = entry["arms"]["base"]["median_process_p50_ns"]
        cand = entry["arms"]["cand"]["median_process_p50_ns"]
        change = entry["median_paired_change_pct"]
        interval = entry["bootstrap95_median_paired_change_pct"]["p50"]
        events = counters.get(case, {})
        instructions = events.get("instructions:u", {}).get("median_change_pct")
        cycles = events.get("cycles:u", {}).get("median_change_pct")
        fmt = lambda value: "n/a" if value is None else f"{value:+.2f}%"
        rows.append(
            f"| `{case}` | {base:,.0f} | {cand:,.0f} | {change['p50']:+.2f}% [{interval[0]:+.2f}, {interval[1]:+.2f}] "
            f"| {change['mean']:+.2f}% | {change['p95']:+.2f}% | {fmt(instructions)} | {fmt(cycles)} |"
        )
    return "\n".join(rows)


def counter_table(counters):
    rows = [
        "| Case | instructions:u base → cand | Δ | cycles:u base → cand | Δ | page faults base → cand |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for case, events in counters.items():
        base_i = statistics.median(events["instructions:u"]["base"])
        cand_i = statistics.median(events["instructions:u"]["cand"])
        base_c = statistics.median(events["cycles:u"]["base"])
        cand_c = statistics.median(events["cycles:u"]["cand"])
        base_p = statistics.median(events["page-faults"]["base"])
        cand_p = statistics.median(events["page-faults"]["cand"])
        rows.append(
            f"| `{case}` | {base_i:,.0f} → {cand_i:,.0f} | {events['instructions:u']['median_change_pct']:+.2f}% "
            f"| {base_c:,.0f} → {cand_c:,.0f} | {events['cycles:u']['median_change_pct']:+.2f}% | {base_p:.1f} → {cand_p:.1f} |"
        )
    return "\n".join(rows)


def flags_table(analysis):
    by_case = {}
    for flag in analysis["flags_above_plus_5_pct"]:
        by_case.setdefault(flag["case"], []).append(flag)
    rows = ["| Case | Flags | Rounds | Largest |", "|---|---:|---|---:|"]
    for case, flags in sorted(by_case.items(), key=lambda item: -len(item[1])):
        rounds = sorted({flag["round"] for flag in flags})
        largest = max(flags, key=lambda flag: flag["change_pct"])
        rows.append(
            f"| `{case}` | {len(flags)} | {', '.join(str(r) for r in rounds)} | {largest['metric']} {largest['change_pct']:+.1f}% (round {largest['round']}) |"
        )
    return "\n".join(rows)


def main():
    packet = sys.argv[1]
    matrix = load(f"{packet}/matrix/analysis.json")
    counters = load(f"{packet}/counters/counters.json")["summary"]
    matrix_v1 = load(f"{packet}/matrix-v1/analysis.json")
    counters_v1 = load(f"{packet}/counters-v1/counters.json")["summary"]
    allocation = load(f"{packet}/allocation/allocation.json")
    lanes = load(f"{packet}/lanes/analysis.json")
    callgrind = load(f"{packet}/callgrind/doc-semantic-open-large.json")
    out = ["# 0769 evidence summary", ""]
    out += ["Generated by `scripts/summarize.py` from the packet's analysis files.", ""]
    out += ["## Correctness lanes (base 97e558cef4, candidate ebf20bba87)", ""]
    census, verdicts, sweep = lanes["census"], lanes["verdicts"], lanes["sweep"]
    out += ["| Census (1,831 files, six readers per stream) | Admitted | Refused at open | Streams of admitted files | Streams a reader refused | Files whose readers disagree |",
            "|---|---:|---:|---:|---:|---:|"]
    for arm in ("base", "cand"):
        c = census[arm]
        out.append(f"| {arm} | {c['admitted']:,} | {c['files'] - c['admitted']:,} | {c['streams']:,} | "
                   f"{c['admitted_streams_a_reader_refused']} | {c['files_disagreeing']} |")
    out += ["", "| Lane | Arm | Admitted | Refused | Reads returned | Reads refused | Admitted, then a read refused | Readers disagree |",
            "|---|---|---:|---:|---:|---:|---:|---:|"]
    for arm in ("base", "cand"):
        v = verdicts[arm]
        out.append(f"| fault lane (30,504 cases) | {arm} | {v['opened']:,} | {v['refused']:,} | {v['reads_ok']:,} | {v['reads_err']:,} | "
                   f"{v.get('opened_then_read_refused', 0)} cases | — |")
    for arm in ("base", "cand"):
        s = sweep[arm]
        out.append(f"| root-size sweep (21,741 copies) | {arm} | {s['admitted']:,} | {s['refused']:,} | {s['reads_ok']:,} | {s['reads_err']:,} | "
                   f"{s['admitted_then_a_read_refused']:,} copies | {s['readers_disagree']:,} copies |")
    out += ["", f"- Census files whose results differ between the arms: {[d['path'] for d in census['differing_files']]}.",
            f"- Fault lane: the base arm reproduces record 0767's recorded outputs: {verdicts['base_reproduces_0767_recorded_outputs']}. "
            f"Changes: {verdicts['changes']}; unexplained: {len(verdicts['unexplained_changes'])}; candidate cases admitted and then refused: {len(verdicts['cand_opened_then_read_refused'])}.",
            f"- Sweep changes: {sweep['changes']}; unexplained: {len(sweep['unexplained_changes'])}.",
            f"- Sweep, candidate against the independent byte-bound oracle: {sweep['cand_against_oracle']}; mismatches: {len(sweep['oracle_mismatches'])}.",
            ""]
    out += ["## Timing (retained candidate, 16 ABBA rounds, core 30)", "",
            "Δ is the median of per-round paired changes; the interval is a 10,000-resample bootstrap of that median (seed 769). "
            "Instructions and cycles are per owner from `counters/` (harness rows include untimed per-iteration setup).", "",
            timing_table(matrix, counters), "",
            f"All probe outputs identical across arms: {matrix['all_probe_outputs_identical_across_arms']}.", ""]
    out += ["## Per-owner counters (retained candidate)", "", counter_table(counters), ""]
    out += ["## Per-round flags above +5% (retained candidate)", "",
            f"{len(matrix['flags_above_plus_5_pct'])} flags; `matrix/analysis.json` lists each with its values.", "",
            flags_table(matrix), ""]
    out += ["## First version (d13c52a45f): timing and counters", "",
            timing_table(matrix_v1, counters_v1), "",
            f"{len(matrix_v1['flags_above_plus_5_pct'])} flags.", ""]
    out += ["## Callgrind: harness `doc_semantic_open/large` (3 samples)", "",
            "| Arm | Program Ir | DOC parse inclusive Ir (`from_ole_with_options`) |", "|---|---:|---:|"]
    for arm, entry in callgrind["arms"].items():
        out.append(f"| {arm} | {entry['program_total_ir']:,} | {entry['doc_parse_inclusive_ir']:,} |")
    out += ["", "Largest self-cost changes, candidate against base:", "",
            "| Function | Δ Ir | Base Ir | Cand Ir |", "|---|---:|---:|---:|"]
    for row in callgrind["largest_self_cost_changes_cand_vs_base"][:10]:
        out.append(f"| `{row['function'][:110]}` | {row['delta_ir']:+,} | {row['base_ir']:,} | {row['cand_ir']:,} |")
    out += ["", "## Allocation (one counting-allocator process per case and arm, five owners)", "",
            "| Case | Same output | Owners identical | Δ bytes | Δ calls | Δ peak live |", "|---|---|---|---:|---:|---:|"]
    for case, arms in allocation.items():
        delta = arms["delta"]
        same_owners = arms["base"]["owners_identical"] and arms["cand"]["owners_identical"]
        out.append(f"| `{case}` | {arms['same_output']} | {same_owners} | {delta['allocated_bytes']:+,} | {delta['allocation_calls']:+,} | {delta['peak_live_bytes']:+,} |")
    print("\n".join(out))


if __name__ == "__main__":
    main()
