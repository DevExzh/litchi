#!/usr/bin/env python3
"""Verify a complete sealed 0457 bundle from a fresh temporary copy.

The copy is made before this driver's own receipt is written.  The proof
therefore records the copied seal as an input observation; the exact root seal
must be regenerated by final verification after this proof and cleanup receipts
are retained.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
from typing import Any


ROOT = Path(__file__).resolve().parent
RECEIPT = ROOT / "portable-verification.json"
PRE = ROOT / "precleanup.json"


def now() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


def sha(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def fail(message: str) -> "NoReturn":
    raise SystemExit(message)


def regular(path: Path, label: str) -> Path:
    if not path.is_file() or path.is_symlink():
        fail(f"{label} is missing, not regular, or a symlink: {path}")
    return path


def load(path: Path, label: str) -> dict[str, Any]:
    regular(path, label)
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        fail(f"{label} is invalid JSON: {error}")
    if not isinstance(value, dict):
        fail(f"{label} must contain a JSON object")
    return value


def safe_verifier(relative: str, expected_sha: str) -> Path:
    if Path(relative).is_absolute() or ".." in Path(relative).parts:
        fail("precleanup verifier path must be bundle-relative")
    candidate = (ROOT / relative).resolve()
    if not candidate.is_relative_to(ROOT.resolve()):
        fail("precleanup verifier path escapes the change-0457 bundle")
    regular(candidate, "precleanup verifier")
    if sha(candidate) != expected_sha:
        fail("root verifier changed after precleanup")
    return candidate


def reject_symlinks(root: Path) -> None:
    if root.is_symlink():
        fail(f"bundle root is a symlink: {root}")
    for directory, names, files in os.walk(root, followlinks=False):
        for name in (*names, *files):
            path = Path(directory) / name
            if path.is_symlink():
                fail(f"bundle contains a symlink: {path}")


def output_status(raw: str) -> Any:
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verifier", help="override the verifier path recorded by precleanup")
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    if RECEIPT.exists():
        fail(f"refusing to overwrite retained receipt: {RECEIPT}")
    pre = load(PRE, "precleanup receipt")
    if pre.get("status") != "pass" or pre.get("exit_code") != 0:
        fail("precleanup receipt is not a passing verifier result")
    relative = args.verifier or pre.get("verifier_path")
    if not isinstance(relative, str) or not relative:
        fail("precleanup receipt has no root verifier path")
    expected_sha = pre.get("verifier_sha256")
    if not isinstance(expected_sha, str) or len(expected_sha) != 64:
        fail("precleanup receipt has no valid root verifier hash")
    verifier = safe_verifier(relative, expected_sha)
    seal = regular(ROOT / "SHA256SUMS", "root bundle seal")
    reject_symlinks(ROOT)
    seal_before = sha(seal)
    started = now()
    command: list[str] = []
    result: subprocess.CompletedProcess[str] | None = None
    verifier_output: Any = None
    temporary_directory_absent = False
    try:
        with tempfile.TemporaryDirectory(prefix="litchi-0457-portable-") as directory:
            parent = Path(directory)
            target = parent / ROOT.name
            shutil.copytree(ROOT, target, symlinks=False)
            reject_symlinks(target)
            copied_verifier = target / relative
            copied_seal = regular(target / "SHA256SUMS", "copied root bundle seal")
            command = [sys.executable, "-B", str(copied_verifier), "--portable"]
            environment = os.environ.copy()
            environment["PYTHONPATH"] = ""
            environment["PYTHONDONTWRITEBYTECODE"] = "1"
            result = subprocess.run(command, cwd=parent, env=environment, capture_output=True, text=True, errors="replace")
            verifier_output = output_status(result.stdout)
            copy_seal_after = sha(copied_seal)
            copy_seal_unchanged = copy_seal_after == seal_before
            cwd = str(parent)
            copied_verifier_sha = sha(copied_verifier)
            copied_seal_bytes = copied_seal.stat().st_size
        temporary_directory_absent = not parent.exists()
    except OSError as error:
        cwd = None
        copied_verifier_sha = None
        copied_seal_bytes = None
        copy_seal_after = None
        copy_seal_unchanged = None
        result = None
        verifier_output = None
        error_text = str(error)
    else:
        error_text = ""
    record: dict[str, Any] = {
        "schema": "litchi-0457-portable-verification-v1",
        "change": 457,
        "status": "pass" if result is not None and result.returncode == 0 and isinstance(verifier_output, dict) and verifier_output.get("status") == "pass" else "failed",
        "argv": command,
        "cwd": cwd,
        "verifier_path": relative,
        "verifier_sha256": expected_sha,
        "copied_verifier_sha256": copied_verifier_sha,
        "driver_sha256": sha(Path(__file__).resolve()),
        "copy_seal_path": "SHA256SUMS",
        "copy_seal_sha256": seal_before,
        "copy_seal_sha256_after": copy_seal_after,
        "copy_seal_bytes": copied_seal_bytes,
        "copy_seal_unchanged": copy_seal_unchanged,
        "started_utc": started,
        "finished_utc": now(),
        "exit_code": result.returncode if result is not None else None,
        "stdout": result.stdout if result is not None else "",
        "stderr": (result.stderr if result is not None else error_text),
        "verifier_output": verifier_output,
        "temporary_directory_absent": temporary_directory_absent,
        "mode": "complete sealed change-0457 bundle copied to a fresh temporary directory",
    }
    with RECEIPT.open("x", encoding="utf-8") as output:
        output.write(json.dumps(record, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({key: record[key] for key in ("status", "exit_code", "copy_seal_sha256", "temporary_directory_absent")}, sort_keys=True))
    return 0 if record["status"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())
