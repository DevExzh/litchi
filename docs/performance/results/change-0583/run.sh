#!/usr/bin/env bash
# Reproduce change 0583's gate in full.
#
#   run.sh <work-dir>
#
# Change 0583 is a one-function fix layered on change 0580, which is itself
# uncommitted at the time of writing.  Everything is built from `git archive`
# extractions of the committed revision 93a610ded with the working tree's two
# soapberry-zip files overlaid, each with its own CARGO_TARGET_DIR.  Nothing is
# built against the shared working tree.
#
# Three trees:
#
#   before        93a610ded, unmodified.  This is change 0582's "before" and
#                 the baseline every divergence count is measured against.
#   fixed         93a610ded + the working tree's archive.rs and office.rs,
#                 i.e. change 0580 *and* change 0583.
#   prefix-tests  93a610ded + change 0580's archive.rs + the working tree's
#                 office.rs.  The whole production fix is in archive.rs and the
#                 whole test addition is in office.rs, so this tree runs change
#                 0583's tests against the pre-fix code.
#
# The corpus, the harness and the classifier are change 0582's, unchanged.
# RNG_SEED = 0x05820580 regenerates the 22,875-input corpus byte for byte.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../../../.." && pwd)"
R0582="$REPO/docs/performance/results/change-0582"
R0580="$REPO/docs/performance/results/change-0580"
WORK="${1:?usage: run.sh <work-dir>}"
BEFORE_REV=93a610ded
JOBS=8

mkdir -p "$WORK"/{before,fixed,prefix-tests}

# --- the trees --------------------------------------------------------------
# docs/ and media/ are ~7 GiB and are not needed to build soapberry-zip, so they
# are excluded during extraction rather than deleted afterwards -- unpacking them
# first is enough to exhaust a scratch quota.  Two integration tests
# `include_bytes!` one retained corpus under docs/, so restore just that.
for tree in before fixed prefix-tests; do
  git -C "$REPO" archive --format=tar "$BEFORE_REV" \
    | tar -x --exclude='docs/*' --exclude='media/*' -C "$WORK/$tree"
  git -C "$REPO" archive --format=tar "$BEFORE_REV" \
      docs/performance/results/change-0416/corpus | tar -x -C "$WORK/$tree"
done

# fixed = change 0580 + change 0583, both files from the working tree.
cp "$REPO/crates/soapberry-zip/src/archive.rs" "$WORK/fixed/crates/soapberry-zip/src/archive.rs"
cp "$REPO/crates/soapberry-zip/src/office.rs"  "$WORK/fixed/crates/soapberry-zip/src/office.rs"

# prefix-tests = change 0580's archive.rs (the pre-fix production code) with
# change 0583's office.rs (the tests).  prefix_archive.py undoes change 0583's
# two hunks and asserts the result's sha256 against the file change 0582
# measured, so this is that code and not an approximation of it.
cp "$REPO/crates/soapberry-zip/src/office.rs" "$WORK/prefix-tests/crates/soapberry-zip/src/office.rs"
python3 "$HERE/prefix_archive.py" "$REPO/crates/soapberry-zip/src/archive.rs" \
        "$WORK/prefix-tests/crates/soapberry-zip/src/archive.rs"

for tree in before fixed; do
  mkdir -p "$WORK/$tree/crates/soapberry-zip/examples"
  cp "$R0582/strict_scope_differential.rs" "$WORK/$tree/crates/soapberry-zip/examples/"
done

# --- corpus (change 0582's, regenerated byte for byte) ----------------------
rm -rf "$WORK/corpus"
python3 "$R0582/build_corpus.py" "$REPO" "$WORK/corpus"

# --- the differential, one cargo process at a time --------------------------
for tree in before fixed; do
  ( cd "$WORK/$tree" && CARGO_TARGET_DIR="$WORK/target-$tree" \
      cargo build --release -p soapberry-zip --example strict_scope_differential -j "$JOBS" )
  "$WORK/target-$tree/release/examples/strict_scope_differential" \
      "$WORK/corpus" "$WORK/report-$tree.txt"
done

python3 "$R0582/classify.py" "$WORK/report-before.txt" "$WORK/report-fixed.txt" \
    "$WORK/divergences.tsv" > "$WORK/classification-summary.json"

# How much of the delta change 0583 moved, relative to change 0580 alone.  This
# needs change 0582's own after report; regenerate it by overlaying the pre-fix
# archive.rs on a fourth tree, or reuse a retained one.
if [ -f "${REPORT_0580:-}" ]; then
  python3 "$HERE/delta.py" "$WORK/report-before.txt" "$REPORT_0580" \
      "$WORK/report-fixed.txt" "$R0582" > "$WORK/delta-summary.json"
fi

# --- corpus convergence: change 0580's own census probe, on the fixed tree ---
rm -rf "$WORK/census"
cp -a "$WORK/fixed" "$WORK/census"
rm -f "$WORK/census/crates/soapberry-zip/examples/strict_scope_differential.rs"
python3 "$R0580/make_strict_scope_probe.py" "$WORK/census/crates/soapberry-zip/src/office.rs"
( cd "$WORK/census" && CARGO_TARGET_DIR="$WORK/target-census" \
    cargo test -p soapberry-zip --lib zz_target_scoped -- --nocapture --test-threads=1 ) \
    > "$WORK/probe-raw.txt" 2>&1 || true
grep -oE "CENSUS[A-Z]* .*" "$WORK/probe-raw.txt" > "$WORK/census-fixed.txt"
grep -oE "SCOPE .*"          "$WORK/probe-raw.txt" > "$WORK/scope-fixed.txt"
diff "$R0580/census-after.txt" "$WORK/census-fixed.txt" && echo "census: byte-identical to change 0580"
diff "$R0580/scope-after.txt"  "$WORK/scope-fixed.txt"  && echo "scope:  byte-identical to change 0580"

# --- the three residuals change 0583 does not close -------------------------
mkdir -p "$WORK/residual/crafted"
python3 "$HERE/residual_witness.py" "$R0582" "$WORK/residual/crafted"
"$WORK/target-before/release/examples/strict_scope_differential" \
    "$WORK/residual" "$WORK/residual-report-before.txt"
"$WORK/target-fixed/release/examples/strict_scope_differential" \
    "$WORK/residual" "$WORK/residual-report-fixed.txt"

# --- the tests --------------------------------------------------------------
NEW_TESTS="a_predecessor_whose_local_compressed_size_reaches_the_target_is_refused \
  a_descriptor_bearing_predecessors_payload_end_is_not_moved \
  a_descriptor_bearing_predecessors_local_size_is_not_a_span_length \
  a_predecessor_whose_local_compressed_size_understates_keeps_the_central_bound \
  a_local_zip64_size_sentinel_is_not_a_neighbour_span_length \
  a_predecessor_local_uncompressed_size_does_not_move_the_payload"

# The six new tests against the pre-fix code: exactly one must fail.
( cd "$WORK/prefix-tests" && CARGO_INCREMENTAL=0 CARGO_TARGET_DIR="$WORK/target-prefix" \
    cargo test -p soapberry-zip --lib -- --test-threads=1 $NEW_TESTS ) \
  > "$WORK/prechange-tests.txt" 2>&1 || true

# Every regression guard against a mutant of the shipped fix.  A test no mutant
# kills pins nothing.
rm -rf "$WORK/mutant"; cp -a "$WORK/fixed" "$WORK/mutant"
for mutant in prefix max-everywhere local-only sentinel-literal usize-max; do
  python3 "$HERE/mutate.py" "$WORK/fixed/crates/soapberry-zip/src/archive.rs" \
      "$WORK/mutant/crates/soapberry-zip/src/archive.rs" "$mutant"
  echo "=== mutant: $mutant ==="
  ( cd "$WORK/mutant" && CARGO_INCREMENTAL=0 CARGO_TARGET_DIR="$WORK/target-mutant" \
      cargo test -p soapberry-zip --lib -- --test-threads=1 $NEW_TESTS ) || true
done

( cd "$WORK/fixed" && cargo fmt -p soapberry-zip -- --check )
for crate in soapberry-zip litchi-opc litchi-ooxml-common litchi-xlsx litchi-docx litchi-pptx; do
  ( cd "$WORK/fixed" && CARGO_INCREMENTAL=0 CARGO_TARGET_DIR="$WORK/target-fixed" \
      cargo test -p "$crate" -j "$JOBS" )
done
( cd "$WORK/fixed" && CARGO_TARGET_DIR="$WORK/target-fixed" \
    cargo clippy -p soapberry-zip --all-targets -j "$JOBS" -- -D warnings )

echo
echo "classification: $WORK/classification-summary.json"
echo "census:         $WORK/census-fixed.txt"
echo "residuals:      $WORK/residual-report-before.txt $WORK/residual-report-fixed.txt"
echo "pre-fix tests:  $WORK/prechange-tests.txt"
