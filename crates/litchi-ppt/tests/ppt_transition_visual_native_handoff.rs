#![allow(
    clippy::expect_used,
    reason = "test and explicitly invoked handoff assertions panic on failure by design"
)]

//! Exact public-API contract for an external same-format PPT resave.
//!
//! The mutation replaces only the canonical visual transition fields. Ignored
//! helpers stop at the filesystem boundary; an external harness owns any
//! native resave and evidence capture.

use std::path::{Path, PathBuf};

use litchi_ppt::package::edit::Error as EditError;
use litchi_ppt::slide_order::{Error, Position, Refusal, SlideTransitionVisual, Snapshot};
use litchi_ppt::{OpenOptions, Package, TransitionDirection, TransitionSpeed, TransitionType};

const GENERATED_PATH_ENV: &str = "LITCHI_PPT_GENERATED_ARTIFACT";
const NATIVE_PATH_ENV: &str = "LITCHI_PPT_NATIVE_ARTIFACT";

fn source_fixture() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../test-data/poi/test-data/slideshow/45543.ppt")
}

fn source_position() -> Position {
    Position::new(0)
}

fn before_visual() -> SlideTransitionVisual {
    SlideTransitionVisual::new(
        TransitionType::Box,
        TransitionDirection::Out,
        TransitionSpeed::Slow,
    )
    .expect("fixture visual transition is exact")
}

fn after_visual() -> SlideTransitionVisual {
    SlideTransitionVisual::new(
        TransitionType::Cover,
        TransitionDirection::FromLeft,
        TransitionSpeed::Medium,
    )
    .expect("handoff visual transition is exact")
}

fn visual_of(bytes: &[u8]) -> SlideTransitionVisual {
    Snapshot::from_bytes_with_options(bytes.to_vec(), OpenOptions::new())
        .expect("fully reopen PPT bytes")
        .slide_transition_visual(source_position())
        .expect("read visual transition")
}

fn generate(source: &Path) -> litchi_ppt::Commit {
    let bytes = std::fs::read(source).expect("read genuine producer PPT fixture");
    assert_eq!(visual_of(&bytes), before_visual());
    let package = Package::from_bytes(&bytes).expect("open genuine producer PPT fixture");
    let mut edit = package.edit().expect("start primary edit");
    edit.set_slide_transition_visual(source_position(), after_visual())
        .expect("stage fixed-width visual transition replacement");
    edit.commit().expect("publish and fully reopen PPT")
}

fn assert_readback(path: &Path) {
    let bytes = std::fs::read(path).expect("read candidate PPT artifact");
    assert_eq!(visual_of(&bytes), after_visual());
}

#[test]
fn genuine_visual_transition_reopens_and_reverses_exactly() {
    let source_bytes = std::fs::read(source_fixture()).expect("read genuine producer PPT fixture");
    let source = Package::from_bytes(&source_bytes).expect("open genuine producer PPT fixture");
    let commit = generate(&source_fixture());
    assert!(commit.diagnostics().changed());
    let generated = commit.package().to_bytes().expect("generated bytes");
    assert_eq!(visual_of(&generated), after_visual());

    let replayed = source
        .apply(commit.patch())
        .expect("apply exact patch")
        .into_package();
    assert_eq!(replayed.to_bytes().expect("replayed bytes"), generated);
    let restored = commit
        .package()
        .apply(&commit.patch().inverse())
        .expect("apply exact inverse")
        .into_package();
    assert_eq!(restored.to_bytes().expect("restored bytes"), source_bytes);
}

#[test]
fn visual_transition_refusals_are_typed_and_failure_atomic() {
    assert!(
        SlideTransitionVisual::new(
            TransitionType::Cover,
            TransitionDirection::None,
            TransitionSpeed::Medium,
        )
        .is_err()
    );

    let bytes = std::fs::read(
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../test-data/ole/ppt/SampleShow.ppt"),
    )
    .expect("read genuine PPT without canonical visual owner");
    assert!(matches!(
        Snapshot::from_bytes_with_options(bytes.clone(), OpenOptions::new())
            .expect("open genuine PPT without canonical visual owner")
            .slide_transition_visual(source_position()),
        Err(Error::Refused(
            Refusal::UnsupportedSlideTransitionVisual { position }
        )) if position == source_position()
    ));
    let package = Package::from_bytes(&bytes).expect("open genuine PPT");
    let mut edit = package.edit().expect("start primary edit");
    assert!(matches!(
        edit.set_slide_transition_visual(source_position(), after_visual()),
        Err(EditError::Native(Error::Refused(
            Refusal::UnsupportedSlideTransitionVisual { position }
        ))) if position == source_position()
    ));
    let commit = edit.commit().expect("commit unchanged edit");
    assert!(!commit.diagnostics().changed());
    assert_eq!(commit.package().to_bytes().expect("unchanged bytes"), bytes);
}

#[test]
#[ignore = "writes the Litchi-generated artifact path requested by an external harness"]
fn generate_litchi_changed_artifact() {
    let output = std::env::var_os(GENERATED_PATH_ENV)
        .map(PathBuf::from)
        .expect("set LITCHI_PPT_GENERATED_ARTIFACT to an explicit output file");
    let generated = generate(&source_fixture())
        .into_package()
        .to_bytes()
        .expect("generated bytes");
    std::fs::write(output, generated).expect("write Litchi-generated PPT artifact");
}

#[test]
#[ignore = "reads a native-resaved artifact supplied by an external harness"]
fn read_back_native_resaved_artifact() {
    let input = std::env::var_os(NATIVE_PATH_ENV)
        .map(PathBuf::from)
        .expect("set LITCHI_PPT_NATIVE_ARTIFACT to an explicit input file");
    assert_readback(&input);
}
