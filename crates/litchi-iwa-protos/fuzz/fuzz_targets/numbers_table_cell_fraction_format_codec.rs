#![no_main]

//! Strict, source-preserving fuzzing for the native Numbers Fraction
//! `FormatStructArchive` projection.
//!
//! Fraction is a deliberately narrow member of the shared format envelope:
//! native type 262 and one of the nine signed/positive denominator strategies
//! in `fraction_accuracy`.  A legacy field 20
//! (`requires_fraction_replacement`) is accepted only when it carries the
//! canonical false value; that exact source span is retained by rewrites and
//! never synthesized by a canonical writer.  This target keeps that family
//! boundary explicit while exercising source-preserving rewrites,
//! unknown-span retention, and finite resource contracts.

use std::{hint::black_box, sync::OnceLock};

use libfuzzer_sys::fuzz_target;
use litchi_iwa_protos::numbers_table_cell_fraction_format_codec as codec;

const MAX_INPUT_BYTES: usize = 64 * 1024;
const MAX_OUTPUT_BYTES: usize = 128 * 1024;
const MAX_FIELDS: usize = 16 * 1024;
const MAX_WORK_BYTES: usize = 512 * 1024;
const MAX_RECURSION: u32 = 64;

const ALL_ACCURACIES: &[u32] = &[
    codec::NATIVE_FRACTION_UP_TO_ONE_DIGIT,
    codec::NATIVE_FRACTION_UP_TO_TWO_DIGITS,
    codec::NATIVE_FRACTION_UP_TO_THREE_DIGITS,
    codec::NATIVE_FRACTION_HALVES,
    codec::NATIVE_FRACTION_QUARTERS,
    codec::NATIVE_FRACTION_EIGHTHS,
    codec::NATIVE_FRACTION_SIXTEENTHS,
    codec::NATIVE_FRACTION_TENTHS,
    codec::NATIVE_FRACTION_HUNDREDTHS,
];

const CANONICAL_UP_TO_ONE_DIGIT: &[u8] = &[0x08, 0x86, 0x02, 0x58, 0xff, 0xff, 0xff, 0xff, 0x0f];
const CANONICAL_UP_TO_TWO_DIGITS: &[u8] = &[0x08, 0x86, 0x02, 0x58, 0xfe, 0xff, 0xff, 0xff, 0x0f];
const CANONICAL_UP_TO_THREE_DIGITS: &[u8] = &[0x08, 0x86, 0x02, 0x58, 0xfd, 0xff, 0xff, 0xff, 0x0f];
const CANONICAL_HALVES: &[u8] = &[0x08, 0x86, 0x02, 0x58, 0x02];
const CANONICAL_QUARTERS: &[u8] = &[0x08, 0x86, 0x02, 0x58, 0x04];
const CANONICAL_EIGHTHS: &[u8] = &[0x08, 0x86, 0x02, 0x58, 0x08];
const CANONICAL_SIXTEENTHS: &[u8] = &[0x08, 0x86, 0x02, 0x58, 0x10];
const CANONICAL_TENTHS: &[u8] = &[0x08, 0x86, 0x02, 0x58, 0x0a];
const CANONICAL_HUNDREDTHS: &[u8] = &[0x08, 0x86, 0x02, 0x58, 0x64];

const CANONICAL_SOURCES: &[&[u8]] = &[
    CANONICAL_UP_TO_ONE_DIGIT,
    CANONICAL_UP_TO_TWO_DIGITS,
    CANONICAL_UP_TO_THREE_DIGITS,
    CANONICAL_HALVES,
    CANONICAL_QUARTERS,
    CANONICAL_EIGHTHS,
    CANONICAL_SIXTEENTHS,
    CANONICAL_TENTHS,
    CANONICAL_HUNDREDTHS,
];

