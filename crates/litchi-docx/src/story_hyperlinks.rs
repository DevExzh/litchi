const HARD_MAX_SELECTED_RELATIONSHIPS: usize = 4096;
const HARD_MAX_SELECTOR_BYTES: usize = 16 * 1024 * 1024;
const HARD_MAX_CHANGED_STORIES: usize = 64;

/// Whether unsupported package references should reject a plan immediately or
/// be returned as explicit incomplete diagnostics.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mode {
    /// Refuse when the package contains any reference class outside this
    /// narrow story-hyperlink closure.
    Strict,
    /// Build a diagnostic-bearing plan for inspection.  Security-sensitive
    /// and ownership-ambiguous classes still make `Plan::apply` fail closed;
    /// this mode never emits a successful incomplete publication.
    BestEffort,
}

/// A bounded story-hyperlink operation policy.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Limits {
    story: StoryLimits,
    xml: sanitize::Limits,
    max_selected_relationships: usize,
    max_selector_bytes: usize,
    max_changed_stories: usize,
}

impl Default for Limits {
    fn default() -> Self {
        Self {
            story: StoryLimits::default(),
            xml: sanitize::Limits::default(),
            max_selected_relationships: HARD_MAX_SELECTED_RELATIONSHIPS,
            max_selector_bytes: 16 * 1024 * 1024,
            max_changed_stories: HARD_MAX_CHANGED_STORIES,
        }
    }
}

impl Limits {
    /// Borrow the bounded OPC story ownership policy.
    #[must_use]
    pub const fn story_limits(self) -> StoryLimits {
        self.story
    }

    /// Borrow the XML scanner policy.
    #[must_use]
    pub const fn xml_limits(self) -> sanitize::Limits {
        self.xml
    }

    /// Maximum selected relationship records.
    #[must_use]
    pub const fn max_selected_relationships(self) -> usize {
        self.max_selected_relationships
    }

    /// Maximum aggregate selector bytes.
    #[must_use]
    pub const fn max_selector_bytes(self) -> usize {
        self.max_selector_bytes
    }

    /// Maximum number of story parts regenerated by one publication.
    #[must_use]
    pub const fn max_changed_stories(self) -> usize {
        self.max_changed_stories
    }

    /// Replace the story ownership policy after validating its hard bounds.
    pub fn with_story_limits(mut self, story: StoryLimits) -> Result<Self> {
        self.story = story.validate()?;
        Ok(self)
    }

    /// Replace the XML scanner policy.
    pub fn with_xml_limits(mut self, xml: sanitize::Limits) -> Result<Self> {
        self.xml = xml;
        Ok(self)
    }

    /// Set the maximum selected relationship records.
    pub fn with_max_selected_relationships(mut self, value: usize) -> Result<Self> {
        if value == 0 || value > HARD_MAX_SELECTED_RELATIONSHIPS {
            return Err(invalid(format!(
                "story hyperlink selected relationship limit must be in 1..={HARD_MAX_SELECTED_RELATIONSHIPS}, got {value}"
            )));
        }
        self.max_selected_relationships = value;
        Ok(self)
    }

    /// Set the maximum aggregate selector bytes.
    pub fn with_max_selector_bytes(mut self, value: usize) -> Result<Self> {
        if value == 0 || value > HARD_MAX_SELECTOR_BYTES {
            return Err(invalid(format!(
                "story hyperlink selector-byte limit must be in 1..={HARD_MAX_SELECTOR_BYTES}, got {value}"
            )));
        }
        self.max_selector_bytes = value;
        Ok(self)
    }

    /// Set the maximum number of regenerated story parts.
    pub fn with_max_changed_stories(mut self, value: usize) -> Result<Self> {
        if value == 0 || value > HARD_MAX_CHANGED_STORIES {
            return Err(invalid(format!(
                "story hyperlink changed-story limit must be in 1..={HARD_MAX_CHANGED_STORIES}, got {value}"
            )));
        }
        self.max_changed_stories = value;
        Ok(self)
    }

    fn validate(self) -> Result<Self> {
        self.story.validate()?;
        if self.max_selected_relationships == 0
            || self.max_selected_relationships > HARD_MAX_SELECTED_RELATIONSHIPS
            || self.max_selector_bytes == 0
            || self.max_selector_bytes > HARD_MAX_SELECTOR_BYTES
            || self.max_changed_stories == 0
            || self.max_changed_stories > HARD_MAX_CHANGED_STORIES
        {
            return Err(invalid("story hyperlink limits exceed their hard bounds"));
        }
        Ok(self)
    }
}

/// Reference classes which are deliberately outside the supported story
/// hyperlink closure.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum UnsupportedClass {
    /// A field, DDE, or instruction-bearing field element was found.
    FieldOrDde,
    /// Markup-compatibility syntax could alter the bytes being edited.
    MarkupCompatibility,
    /// Attached template relationship or element.
    AttachedTemplate,
    /// Mail-merge relationship or settings element.
    MailMerge,
    /// Document or write protection is present.
    Protection,
    /// Macro-enabled or VBA-bearing content is present.
    Macro,
    /// Embedded OLE/package/ActiveX content is present.
    EmbeddedContent,
    /// Digital-signature infrastructure is present.
    Signature,
    /// An external relationship is owned outside a story hyperlink.
    NonStoryExternal,
    /// Story ownership is missing, duplicated, or otherwise ambiguous.
    UnknownOwner,
    /// The source is encrypted or is not a plaintext OPC package.
    EncryptedSource,
}

/// Counted, content-free diagnostic for an incomplete inventory.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Diagnostic {
    class: UnsupportedClass,
    count: usize,
}

impl Diagnostic {
    /// Reference class represented by this diagnostic.
    #[must_use]
    pub const fn class(self) -> UnsupportedClass {
        self.class
    }

    /// Number of occurrences folded into this diagnostic.
    #[must_use]
    pub const fn count(self) -> usize {
        self.count
    }
}

