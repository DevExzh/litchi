fn add_diagnostic(
    diagnostics: &mut Vec<Diagnostic>,
    class: UnsupportedClass,
    count: usize,
) -> Result<()> {
    if let Some(existing) = diagnostics
        .iter_mut()
        .find(|diagnostic| diagnostic.class == class)
    {
        existing.count = existing
            .count
            .checked_add(count)
            .ok_or_else(|| invalid("story hyperlink diagnostic count overflows usize"))?;
        return Ok(());
    }
    diagnostics
        .try_reserve(1)
        .map_err(|source| Error::Allocation {
            resource: "story hyperlink diagnostics",
            source,
        })?;
    diagnostics.push(Diagnostic { class, count });
    Ok(())
}

fn coalesce_diagnostics(mut diagnostics: Vec<Diagnostic>) -> Result<Vec<Diagnostic>> {
    diagnostics.sort_unstable_by_key(|diagnostic| diagnostic.class);
    let mut output: Vec<Diagnostic> = Vec::new();
    output
        .try_reserve_exact(diagnostics.len())
        .map_err(|source| Error::Allocation {
            resource: "story hyperlink diagnostic order",
            source,
        })?;
    for diagnostic in diagnostics {
        if let Some(previous) = output.last_mut() {
            if previous.class == diagnostic.class {
                previous.count = previous
                    .count
                    .checked_add(diagnostic.count)
                    .ok_or_else(|| invalid("story hyperlink diagnostic count overflows usize"))?;
                continue;
            }
        }
        output.push(diagnostic);
    }
    Ok(output)
}

fn owned_str(value: &str, resource: &'static str) -> Result<String> {
    let mut owned = String::new();
    owned
        .try_reserve_exact(value.len())
        .map_err(|source| Error::Allocation { resource, source })?;
    owned.push_str(value);
    Ok(owned)
}

fn copy_bytes(bytes: &[u8], resource: &'static str) -> Result<Vec<u8>> {
    let mut copy = Vec::new();
    copy.try_reserve_exact(bytes.len())
        .map_err(|source| Error::Allocation { resource, source })?;
    copy.extend_from_slice(bytes);
    Ok(copy)
}

fn clone_relationship(relationship: &RelationshipState) -> Result<RelationshipState> {
    Ok(RelationshipState::new(
        owned_str(
            relationship.id(),
            "story hyperlink retained relationship ID",
        )?,
        owned_str(
            relationship.relationship_type(),
            "story hyperlink retained relationship type",
        )?,
        owned_str(
            relationship.target(),
            "story hyperlink retained relationship target",
        )?,
        relationship.is_external(),
    ))
}

fn clone_wrapper(wrapper: &Wrapper) -> Result<Wrapper> {
    Ok(Wrapper {
        open: wrapper.open.clone(),
        close: wrapper.close.clone(),
        relationship_id: owned_str(
            &wrapper.relationship_id,
            "story hyperlink wrapper relationship ID",
        )?,
    })
}

fn owned_uri(value: &PackURI, resource: &'static str) -> Result<String> {
    owned_str(value.as_str(), resource)
}

fn clone_uri(value: &PackURI) -> Result<PackURI> {
    PackURI::new(value.as_str()).map_err(|error| Error::InvalidUri(error.to_string()))
}

fn contains_ascii_case_insensitive(haystack: &str, needle: &str) -> bool {
    haystack
        .as_bytes()
        .windows(needle.len())
        .any(|window| window.eq_ignore_ascii_case(needle.as_bytes()))
}

fn starts_with_ascii_case_insensitive(haystack: &str, needle: &str) -> bool {
    haystack
        .get(..needle.len())
        .is_some_and(|prefix| prefix.eq_ignore_ascii_case(needle))
}

fn unsupported(operation: &'static str, diagnostics: &[Diagnostic]) -> Error {
    let reason = if diagnostics
        .iter()
        .any(|diagnostic| diagnostic.class == UnsupportedClass::UnknownOwner)
    {
        "story package has unsupported or ambiguous reference ownership"
    } else {
        "story package contains external-reference classes outside the supported hyperlink closure"
    };
    Error::UnsafeEdit {
        format: "DOCX",
        operation,
        reason,
    }
}

fn invalid(message: impl Into<String>) -> Error {
    Error::InvalidFormat(message.into())
}

fn limit(resource: &'static str, maximum: usize, actual: usize) -> Error {
    Error::ExternalHyperlinkRedactionLimit {
        resource,
        maximum,
        actual,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn story(part_name: &str) -> StoryInfo {
        StoryInfo {
            part_name: part_name.to_owned(),
            kind: StoryKind::Main,
        }
    }

    fn relationship(
        part_name: &str,
        relationship_id: &str,
        target_url: &str,
    ) -> ExternalHyperlinkRelationship {
        ExternalHyperlinkRelationship {
            part_name: part_name.to_owned(),
            kind: StoryKind::Main,
            relationship_id: relationship_id.to_owned(),
            target_url: target_url.to_owned(),
            wrapper_count: 1,
        }
    }

    #[test]
    fn relationship_indexes_preserve_story_ranges_and_target_order() {
        let stories = [story("/word/header1.xml"), story("/word/document.xml")];
        let relationships = [
            relationship("/word/document.xml", "rId1", "https://z.invalid/"),
            relationship("/word/document.xml", "rId2", "https://a.invalid/"),
            relationship("/word/header1.xml", "rId1", "https://a.invalid/"),
        ];

        let (story_ranges, target_order) =
            build_relationship_indexes(&stories, &relationships).unwrap();

        assert_eq!(
            story_ranges.as_slice(),
            &[
                StoryRelationshipRange { start: 2, end: 3 },
                StoryRelationshipRange { start: 0, end: 2 },
            ]
        );
        let ordered_targets = target_order
            .iter()
            .map(|index| relationships[*index].target_url.as_str())
            .collect::<Vec<_>>();
        assert_eq!(
            ordered_targets,
            [
                "https://a.invalid/",
                "https://a.invalid/",
                "https://z.invalid/",
            ]
        );
    }
}
