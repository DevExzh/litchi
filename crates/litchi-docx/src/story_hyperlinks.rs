/// Complete deterministic story-hyperlink inventory.
#[derive(Clone, Debug)]
pub struct Inventory {
    stories: Arc<Vec<StoryInfo>>,
    relationships: Arc<Vec<ExternalHyperlinkRelationship>>,
    diagnostics: Arc<Vec<Diagnostic>>,
    /// Ranges into `relationships`, aligned with `stories`.
    ///
    /// The public inventory remains an immutable value, while redaction plans
    /// can select the relationships belonging to one story without scanning
    /// every story relationship for each story.  The ranges retain no source
    /// bytes and are bounded by the same relationship/story limits used while
    /// capturing the inventory.
    story_relationships: Arc<Vec<StoryRelationshipRange>>,
    /// Relationship indexes ordered by target URL.  The index stores only
    /// relationship positions, so target strings are not duplicated in the
    /// immutable snapshot.
    target_order: Arc<Vec<usize>>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct StoryRelationshipRange {
    start: usize,
    end: usize,
}

impl Inventory {
    /// Number of reachable stories.
    #[must_use]
    pub fn story_count(&self) -> usize {
        self.stories.len()
    }

    /// Number of external story hyperlink relationships.
    #[must_use]
    pub fn relationship_count(&self) -> usize {
        self.relationships.len()
    }

    /// Reachable stories, ordered main-first and then by Part URI.
    #[must_use]
    pub fn stories(&self) -> &[StoryInfo] {
        &self.stories
    }

    /// External hyperlink relationships ordered by Part URI and relationship ID.
    #[must_use]
    pub fn relationships(&self) -> &[ExternalHyperlinkRelationship] {
        &self.relationships
    }

    /// Explicit unsupported-reference diagnostics.
    #[must_use]
    pub fn diagnostics(&self) -> &[Diagnostic] {
        &self.diagnostics
    }

    /// True only when every scanned package reference belongs to this narrow
    /// supported closure.
    #[must_use]
    pub fn is_complete(&self) -> bool {
        self.diagnostics.is_empty()
    }
}

/// Predicted or applied effects of one story-hyperlink redaction.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct EffectReport {
    selected_targets: usize,
    scanned_stories: usize,
    removed_relationships: usize,
    unwrapped_hyperlinks: usize,
}

impl EffectReport {
    /// Number of distinct exact target URLs selected.
    #[must_use]
    pub const fn selected_targets(self) -> usize {
        self.selected_targets
    }

    /// Number of relationship-owned stories scanned.
    #[must_use]
    pub const fn scanned_stories(self) -> usize {
        self.scanned_stories
    }

    /// Number of external relationship records removed.
    #[must_use]
    pub const fn removed_relationships(self) -> usize {
        self.removed_relationships
    }

    /// Number of visible hyperlink wrappers unwrapped.
    #[must_use]
    pub const fn unwrapped_hyperlinks(self) -> usize {
        self.unwrapped_hyperlinks
    }

    /// True when publication copies the exact source artifact.
    #[must_use]
    pub const fn is_noop(self) -> bool {
        self.removed_relationships == 0 && self.unwrapped_hyperlinks == 0
    }
}

/// Explicit report returned by both best-effort plans and successful commits.
#[derive(Clone, Debug)]
pub struct Report {
    effect: EffectReport,
    diagnostics: Arc<Vec<Diagnostic>>,
    mode: Mode,
}

impl Report {
    /// Deterministic mutation effects.
    #[must_use]
    pub const fn effect(&self) -> EffectReport {
        self.effect
    }

    /// Unsupported classes observed during the package scan.
    #[must_use]
    pub fn diagnostics(&self) -> &[Diagnostic] {
        &self.diagnostics
    }

    /// Whether the report certifies the narrow story-hyperlink scope.
    #[must_use]
    pub fn is_complete(&self) -> bool {
        self.diagnostics.is_empty()
    }

    /// Policy used to produce this report.
    #[must_use]
    pub const fn mode(&self) -> Mode {
        self.mode
    }
}

