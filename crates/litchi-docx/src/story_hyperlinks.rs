//! Source-bound inventory and forward-only redaction of external hyperlinks
//! in relationship-owned WordprocessingML stories.
//!
//! This capability is intentionally separate from the established main-only
//! [`crate::sanitize`] and [`crate::redact`] APIs.  It inventories the main,
//! header, footer, footnote, endnote, comments, and glossary stories reachable
//! through the OPC relationship graph.  Only ordinary external hyperlink
//! relationships represented by `w:hyperlink/@r:id` are supported.  Fields,
//! DDE/mail-merge/template references, embedded or macro content, signatures,
//! protection, MCE, and external references outside the selected story
//! hyperlink closure remain explicit refusals.

