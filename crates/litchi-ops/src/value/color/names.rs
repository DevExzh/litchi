//! Static vocabularies for colors: named colors, scheme and theme slots,
//! system colors and transform names. Every table is sorted by its
//! lower-case ASCII key for allocation-free binary search; the unit tests
//! check the order.

use super::{Rgba, Scheme, System, ThemeSlot, TransformKind};

/// Where a named color comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::value) enum Origin {
    /// A CSS named color that is not a DrawingML preset (`rebeccapurple`).
    Css,
    /// A CSS named color that is also a DrawingML preset color.
    CssAndPreset,
    /// A legacy DrawingML preset spelling (`dkBlue`, `ltGray`, `medPurple`).
    Preset,
    /// The CSS keyword `transparent`: black with alpha 0.
    Transparent,
}

/// One named color.
#[derive(Debug, Clone, Copy)]
pub(in crate::value) struct Named {
    /// The lower-case name.
    pub(in crate::value) name: &'static str,
    pub(in crate::value) rgb: [u8; 3],
    pub(in crate::value) origin: Origin,
    /// The exact `ST_PresetColorVal` token, for preset colors.
    pub(in crate::value) preset: Option<&'static str>,
}

impl Named {
    /// A CSS named color that is not a preset.
    const fn css(name: &'static str, rgb: u32) -> Self {
        Self::new(name, rgb, Origin::Css, None)
    }

    /// A CSS named color that is also a preset color.
    const fn both(name: &'static str, rgb: u32, preset: &'static str) -> Self {
        Self::new(name, rgb, Origin::CssAndPreset, Some(preset))
    }

    /// A legacy preset spelling.
    const fn legacy(name: &'static str, rgb: u32, preset: &'static str) -> Self {
        Self::new(name, rgb, Origin::Preset, Some(preset))
    }

    /// The CSS keyword `transparent`.
    const fn transparent() -> Self {
        Self::new("transparent", 0, Origin::Transparent, None)
    }

    const fn new(
        name: &'static str,
        rgb: u32,
        origin: Origin,
        preset: Option<&'static str>,
    ) -> Self {
        let [_, red, green, blue] = rgb.to_be_bytes();
        Self {
            name,
            rgb: [red, green, blue],
            origin,
            preset,
        }
    }

    /// The color, with alpha 0 for `transparent`.
    pub(in crate::value) const fn rgba(&self) -> Rgba {
        let [red, green, blue] = self.rgb;
        let alpha = match self.origin {
            Origin::Transparent => 0,
            _ => 255,
        };
        Rgba::new(red, green, blue).with_alpha(alpha)
    }
}

