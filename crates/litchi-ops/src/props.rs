    /// Record 0326: a typed length coerces as the text it prints as, value
    /// and error alike, in every length context, whether or not it takes the
    /// direct route.
    #[test]
    fn typed_lengths_coerce_as_their_text() {
        fn outcome(value: &PropValue<'_>, ty: ValueType) -> String {
            match value.with_coerced(ty, |scalar| {
                Ok(match scalar {
                    Some(Scalar::Length(length)) => format!("length {}", length.emu()),
                    other => format!("{other:?}"),
                })
            }) {
                Ok(text) => text,
                Err(error) => format!(
                    "{} {} {:?}",
                    error.code().as_str(),
                    error,
                    error.suggestion()
                ),
            }
        }
        let mut values: Vec<i64> = vec![
            i64::MIN,
            i64::MIN + 1,
            i64::MAX,
            i64::MAX - 1,
            1 << 50,
            (1 << 50) - 1,
            (1 << 50) + 1,
            -(1 << 50),
            1 << 53,
            i64::from(i32::MAX),
            i64::from(i32::MAX) + 1,
            i64::from(i32::MAX) - 1,
            6_349,
            6_350,
            6_351,
            6_477,
            50_800_000,
            50_800_127,
            50_799_873,
        ];
        for step in [
            1_i64, 127, 635, 3_600, 9_525, 12_700, 36_000, 360_000, 914_400,
        ] {
            values.extend((-300..=300).map(|k| k * step));
            values.extend((1..=200).map(|k| k * step * 997));
        }
        let mut seed = 0x9E37_79B9_7F4A_7C15_u64;
        for _ in 0..20_000 {
            seed ^= seed << 13;
            seed ^= seed >> 7;
            seed ^= seed << 17;
            #[allow(clippy::cast_possible_wrap, reason = "any bit pattern is a test value")]
            let raw = seed as i64;
            values.extend([raw, raw >> 20, raw >> 34, (raw >> 40) * 127]);
        }
        let specs = [
            LengthSpec::POSITION,
            LengthSpec::EXTENT,
            LengthSpec::LINE_WIDTH,
            LengthSpec::FONT_SIZE,
            LengthSpec::new(LengthContext::WordSpacing, LengthStyle::Auto),
        ];
        let mut direct = 0;
        for &emu in &values {
            let length = Length::from_emu(emu);
            let text = Scalar::Length(length).display(None).to_string();
            for spec in specs {
                let ty = ValueType::Length(spec);
                if length.coerced_in(spec.context).is_some() {
                    direct += 1;
                }
                assert_eq!(
                    outcome(&PropValue::Length(length), ty),
                    outcome(&PropValue::Text(Cow::Borrowed(&text)), ty),
                    "{emu} EMU ({text}) as {:?}",
                    spec.context
                );
            }
        }
        assert!(direct > values.len(), "{direct}");
    }

    #[test]
    fn scalar_admission_preserves_kinds_and_refuses_lossy_inputs() {
        for text in ["123", "true", "=A1", ""] {
            PropValue::from(text)
                .with_coerced(ValueType::Scalar, |value| {
                    assert!(matches!(value, Some(Scalar::Text(value)) if value == text));
                    Ok(())
                })
                .unwrap();
        }
        PropValue::Int(i64::MAX)
            .with_coerced(ValueType::Scalar, |value| {
                assert!(matches!(value, Some(Scalar::Int(i64::MAX))));
                Ok(())
            })
            .unwrap();
        PropValue::Bool(true)
            .with_coerced(ValueType::Scalar, |value| {
                assert!(matches!(value, Some(Scalar::Bool(true))));
                Ok(())
            })
            .unwrap();
        for value in [
            PropValue::Unsigned(u64::MAX),
            PropValue::WideInt(i128::MAX),
            PropValue::Number(f64::NAN),
            PropValue::Color(Color::rgb(1, 2, 3)),
        ] {
            assert_eq!(
                value
                    .with_coerced(ValueType::Scalar, |_| Ok(()))
                    .unwrap_err()
                    .code(),
                Code::InvalidValue
            );
        }
    }

    fn collect<'a>(input: impl IntoProps<'a>) -> Vec<(String, PropValue<'a>)> {
        input
            .into_props()
            .expect("valid property input")
            .map(|(key, value)| (key.as_str().to_owned(), value))
            .collect()
    }

    #[test]
    fn macro_and_pair_forms_preserve_order_and_borrowing() {
        let owned = String::from("authored text");
        let stack = props! {
            "bold" => true,
            "text" => owned.clone(),
            "count" => 3_i32,
        };
        let pairs = collect(stack);
        assert_eq!(pairs.len(), 3);
        assert_eq!(pairs[0].0, "bold");
        assert_eq!(pairs[0].1, PropValue::Bool(true));
        assert!(matches!(pairs[1].1, PropValue::Text(Cow::Owned(_))));

        let borrowed = [("text", owned.as_str()), ("color", "FF0000")];
        let pairs = collect(&borrowed[..]);
        assert!(matches!(pairs[0].1, PropValue::Text(Cow::Borrowed(_))));
        assert_eq!(pairs[0].1.as_text(), Some("authored text"));
        assert_eq!(pairs[1].1.as_text(), Some("FF0000"));
    }

    #[test]
    fn owned_pair_vectors_and_string_sequences_are_supported() {
        let pairs = collect(vec![
            (String::from("text"), String::from("owned")),
            (String::from("number"), String::from("12")),
        ]);
        assert!(matches!(pairs[0].1, PropValue::Text(Cow::Owned(_))));

        let strings = ["formula==SUM(A1:A3)", "empty="];
        let parsed = collect(strings);
        assert_eq!(parsed[0].0, "formula");
        assert_eq!(parsed[0].1.as_text(), Some("=SUM(A1:A3)"));
        assert_eq!(parsed[1].1.as_text(), Some(""));

        let duplicate = collect(props! { "Bold" => true, "bold" => false });
        assert_eq!(duplicate.len(), 2);
        assert_eq!(duplicate[0].1, PropValue::Bool(true));
        assert_eq!(duplicate[1].1, PropValue::Bool(false));
    }

