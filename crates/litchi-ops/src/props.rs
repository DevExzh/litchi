/// An owned, ordered list of property assignments for batch and node verbs.
///
/// Keys repeat at most by mistake; when one does, ASCII case-insensitively,
/// the last assignment wins, as in OfficeCLI's batch dictionaries
/// ([`Props::get`] answers the same way).
///
/// ```
/// use litchi_ops::props::{Props, PropValue};
///
/// let mut props = Props::new().with("bold", true).with("size", "12pt");
/// props.push("Bold", false);
/// assert_eq!(props.len(), 3);
/// assert_eq!(props.get("BOLD"), Some(&PropValue::Bool(false)));
/// assert_eq!(props.get("italic"), None);
/// let keys: Vec<&str> = props.iter().map(|(key, _)| key.as_str()).collect();
/// assert_eq!(keys, ["bold", "size", "Bold"]);
/// ```
#[derive(Clone, Default, PartialEq)]
pub struct Props<'a> {
    pairs: Vec<(Key<'a>, PropValue<'a>)>,
}

impl fmt::Debug for Props<'_> {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        // Keep property names and values out of logs.  The ordered length is
        // useful for diagnostics without exposing authored content.
        formatter
            .debug_struct("Props")
            .field("len", &self.pairs.len())
            .finish_non_exhaustive()
    }
}

impl<'a> Props<'a> {
    /// An empty list; allocates nothing until the first push.
    #[must_use]
    pub const fn new() -> Self {
        Self { pairs: Vec::new() }
    }

    /// An empty list with room for `capacity` assignments.
    #[must_use]
    pub fn with_capacity(capacity: usize) -> Self {
        Self {
            pairs: Vec::with_capacity(capacity),
        }
    }

    /// The assignments of `props`, collected.
    ///
    /// # Errors
    ///
    /// As [`IntoProps::into_props`].
    ///
    /// ```
    /// use litchi_ops::props::Props;
    ///
    /// let props = Props::from_props(&["bold=true", "color=FF0000"][..])?;
    /// assert_eq!(props.len(), 2);
    /// # Ok::<(), litchi_ops::Error>(())
    /// ```
    pub fn from_props(props: impl IntoProps<'a>) -> Result<Self> {
        Ok(Self {
            pairs: props.into_props()?.collect(),
        })
    }

    /// Appends one assignment.
    pub fn push(&mut self, key: impl Into<Key<'a>>, value: impl Into<PropValue<'a>>) {
        self.pairs.push((key.into(), value.into()));
    }

    /// Appends one assignment, for chaining.
    #[must_use]
    pub fn with(mut self, key: impl Into<Key<'a>>, value: impl Into<PropValue<'a>>) -> Self {
        self.push(key, value);
        self
    }

    /// The number of assignments, repeated keys included.
    #[must_use]
    pub fn len(&self) -> usize {
        self.pairs.len()
    }

    /// Whether there is no assignment.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.pairs.is_empty()
    }

    /// The assignments, in order.
    pub fn iter(&self) -> impl ExactSizeIterator<Item = (&Key<'a>, &PropValue<'a>)> + Clone {
        self.pairs.iter().map(|(key, value)| (key, value))
    }

    /// The assignments, in order, as a slice.
    #[must_use]
    pub fn as_slice(&self) -> &[(Key<'a>, PropValue<'a>)] {
        &self.pairs
    }

    /// The value the last assignment of `key` gives, matching keys ASCII
    /// case-insensitively.
    #[must_use]
    pub fn get(&self, key: &str) -> Option<&PropValue<'a>> {
        self.pairs
            .iter()
            .rev()
            .find(|(candidate, _)| candidate.eq_ignore_ascii_case(key))
            .map(|(_, value)| value)
    }

    /// The same list, owning every key and text.
    #[must_use]
    pub fn into_owned(self) -> Props<'static> {
        Props {
            pairs: self
                .pairs
                .into_iter()
                .map(|(key, value)| (key.into_owned(), value.into_owned()))
                .collect(),
        }
    }
}

impl<'a, K, V> FromIterator<(K, V)> for Props<'a>
where
    K: Into<Key<'a>>,
    V: Into<PropValue<'a>>,
{
    fn from_iter<I: IntoIterator<Item = (K, V)>>(iter: I) -> Self {
        Self {
            pairs: iter
                .into_iter()
                .map(|(key, value)| (key.into(), value.into()))
                .collect(),
        }
    }
}

impl<'a, K, V> Extend<(K, V)> for Props<'a>
where
    K: Into<Key<'a>>,
    V: Into<PropValue<'a>>,
{
    fn extend<I: IntoIterator<Item = (K, V)>>(&mut self, iter: I) {
        self.pairs.extend(
            iter.into_iter()
                .map(|(key, value)| (key.into(), value.into())),
        );
    }
}

impl<'a> IntoIterator for Props<'a> {
    type Item = (Key<'a>, PropValue<'a>);
    type IntoIter = std::vec::IntoIter<(Key<'a>, PropValue<'a>)>;

    fn into_iter(self) -> Self::IntoIter {
        self.pairs.into_iter()
    }
}

impl<'s, 'a> IntoIterator for &'s Props<'a> {
    type Item = &'s (Key<'a>, PropValue<'a>);
    type IntoIter = std::slice::Iter<'s, (Key<'a>, PropValue<'a>)>;

    fn into_iter(self) -> Self::IntoIter {
        self.pairs.iter()
    }
}

/// A value `set` and `add` accept as their property assignments.
///
/// | Form | Example |
/// |---|---|
/// | the [`props!`](crate::props!) macro: an array on the stack | `props!{"font.bold" => true, "size" => Length::from_points(12)}` |
/// | an array, slice or vector of `(key, value)` pairs, `K: Into<Key>` and `V: Into<PropValue>` | `[("font.bold", true)]`, `&[("text", "Hi")][..]`, `vec![(name, value)]` |
/// | OfficeCLI's string form, `key=value`, split at the first `=` | `["bold=true", "size=12pt"]`, `&args[..]` of `String`s |
/// | a [`Props`] list, by value or borrowed | `props`, `&props` |
///
/// Arrays, vectors and `Props` are taken by value. A borrowed slice of
/// pairs needs `Copy` keys and values (`&str`, `bool`, numbers, [`Length`],
/// [`Color`]), so that no assignment is cloned behind the caller's back; a
/// borrowed `Props` lends its keys and values instead. Nothing is allocated
/// beyond what the caller built: the assignments are moved or borrowed, and
/// the string form borrows both halves of each entry.
///
/// The lifetime `'a` is that of the borrowed keys and values; with static
/// keys and owned or `Copy` values it is `'static`.
///
/// ```
/// use litchi_ops::props;
/// use litchi_ops::value::Length;
/// use litchi_ops::props::IntoProps;
///
/// fn keys<'a>(props: impl IntoProps<'a>) -> litchi_ops::Result<Vec<String>> {
///     Ok(props.into_props()?.map(|(key, value)| format!("{key}={value}")).collect())
/// }
///
/// assert_eq!(keys(props! {"font.bold" => true, "size" => Length::from_points(12)})?, ["font.bold=true", "size=12pt"]);
/// assert_eq!(keys([("font.bold", true)])?, ["font.bold=true"]);
/// assert_eq!(keys(&[("text", "Hi"), ("style", "Heading1")][..])?, ["text=Hi", "style=Heading1"]);
/// assert_eq!(keys(["bold=true", "formula==SUM(A1:A3)"])?, ["bold=true", "formula==SUM(A1:A3)"]);
/// let owned = vec![String::from("color=1F4E79")];
/// assert_eq!(keys(&owned)?, ["color=1F4E79"]);
///
/// // A string entry without `=`, or with an empty key, is refused.
/// let error = keys(["bold"]).unwrap_err();
/// assert_eq!(error.code(), litchi_ops::Code::InvalidArgument);
/// # Ok::<(), litchi_ops::Error>(())
/// ```
pub trait IntoProps<'a> {
    /// The assignments, in order.
    ///
    /// # Errors
    ///
    /// [`Code::InvalidArgument`] for an entry of OfficeCLI's string form
    /// that is not `key=value` with a non-empty key. The other forms do not
    /// fail.
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>>;
}

impl<'a, K, V, const N: usize> IntoProps<'a> for [(K, V); N]
where
    K: Into<Key<'a>>,
    V: Into<PropValue<'a>>,
{
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        Ok(self
            .into_iter()
            .map(|(key, value)| (key.into(), value.into())))
    }
}

impl<'a, K, V> IntoProps<'a> for Vec<(K, V)>
where
    K: Into<Key<'a>>,
    V: Into<PropValue<'a>>,
{
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        Ok(self
            .into_iter()
            .map(|(key, value)| (key.into(), value.into())))
    }
}

impl<'a, K, V> IntoProps<'a> for &[(K, V)]
where
    K: Copy + Into<Key<'a>>,
    V: Copy + Into<PropValue<'a>>,
{
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        Ok(self.iter().map(|&(key, value)| (key.into(), value.into())))
    }
}

impl<'a, K, V, const N: usize> IntoProps<'a> for &[(K, V); N]
where
    K: Copy + Into<Key<'a>>,
    V: Copy + Into<PropValue<'a>>,
{
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        self.as_slice().into_props()
    }
}

impl<'a> IntoProps<'a> for Props<'a> {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        Ok(self.pairs.into_iter())
    }
}

impl<'s> IntoProps<'s> for &'s Props<'_> {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'s>, PropValue<'s>)>> {
        Ok(self
            .pairs
            .iter()
            .map(|(key, value)| (key.reborrow(), value.reborrow())))
    }
}

/// Splits one entry of OfficeCLI's string form at its first `=`.
fn split_entry(entry: &str) -> Option<(&str, &str)> {
    entry.split_once('=').filter(|(key, _)| !key.is_empty())
}

/// Checks every entry of OfficeCLI's string form before any is used, so a
/// malformed list is refused as a whole.
fn check_entries<'e>(entries: impl IntoIterator<Item = &'e str>) -> Result<()> {
    for entry in entries {
        if split_entry(entry).is_none() {
            return Err(invalid_entry());
        }
    }
    Ok(())
}

/// One checked entry as an assignment, borrowing both halves.
fn entry_pair(entry: &str) -> (Key<'_>, PropValue<'_>) {
    // `check_entries` ran first, so every entry splits.
    let (key, value) = split_entry(entry).unwrap_or((entry, ""));
    (Key::new(key), PropValue::Text(Cow::Borrowed(value)))
}

impl<'a> IntoProps<'a> for &[&'a str] {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        check_entries(self.iter().copied())?;
        Ok(self.iter().copied().map(entry_pair))
    }
}

impl<'a, const N: usize> IntoProps<'a> for [&'a str; N] {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        check_entries(self)?;
        Ok(self.into_iter().map(entry_pair))
    }
}

impl<'a, const N: usize> IntoProps<'a> for &[&'a str; N] {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        self.as_slice().into_props()
    }
}

impl<'a> IntoProps<'a> for Vec<&'a str> {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        check_entries(self.iter().copied())?;
        Ok(self.into_iter().map(entry_pair))
    }
}

impl<'a> IntoProps<'a> for &'a [String] {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        check_entries(self.iter().map(String::as_str))?;
        Ok(self.iter().map(String::as_str).map(entry_pair))
    }
}

impl<'a> IntoProps<'a> for &'a Vec<String> {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        self.as_slice().into_props()
    }
}

impl<'a, const N: usize> IntoProps<'a> for &'a [String; N] {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        self.as_slice().into_props()
    }
}

/// Splits and owns one `String` entry.  The original entry is consumed so the
/// two output strings reuse its allocation rather than cloning either side.
fn owned_entry_pair<'a>(mut entry: String) -> Option<(Key<'a>, PropValue<'a>)> {
    let at = entry.find('=')?;
    if at == 0 {
        return None;
    }
    let value = entry.split_off(at + 1);
    entry.truncate(at);
    Some((Key::from(entry), PropValue::Text(Cow::Owned(value))))
}

impl<'a> IntoProps<'a> for Vec<String> {
    fn into_props(self) -> Result<impl Iterator<Item = (Key<'a>, PropValue<'a>)>> {
        if self.iter().any(|entry| split_entry(entry).is_none()) {
            return Err(invalid_entry());
        }
        Ok(self.into_iter().map(|entry| {
            // The validation pass above makes this conversion infallible and
            // keeps every entry in its original order.
            owned_entry_pair(entry).expect("validated property entry")
        }))
    }
}

fn invalid_entry() -> Error {
    Error::new(
        Code::InvalidArgument,
        "a property entry must be key=value with a non-empty key",
    )
    .with_suggestion("write each property as key=value")
}

/// Property assignments on the stack, for `set` and `add`: an array of
/// `(key, value)` pairs, each key converted with `Key::from` and each value
/// with `PropValue::from`, so nothing is allocated beyond the values.
///
/// Keys are text (`"font.bold"`, matched ASCII case-insensitively) or typed
/// keys from the registry; values are anything `PropValue` converts from:
/// `bool`, integers, `f64`, `&str`, `String`, a
/// [`Length`](crate::value::Length) or a [`Color`](crate::value::Color).
///
/// ```
/// use litchi_ops::props;
/// use litchi_ops::value::{Color, Length};
/// use litchi_ops::props::{IntoProps, PropValue};
///
/// let assignments = props! {
///     "font.bold" => true,
///     "size" => Length::from_points(12),
///     "color" => Color::rgb(0x1F, 0x4E, 0x79),
///     "text" => "Quarterly results",
///     "spaceAfter" => 6,
/// };
/// assert_eq!(assignments.len(), 5);
/// let (key, value) = &assignments[1];
/// assert_eq!((key.as_str(), value), ("size", &PropValue::Length(Length::from_points(12))));
///
/// // `props!{}` is the empty list.
/// assert_eq!(props! {}.into_props()?.count(), 0);
/// # Ok::<(), litchi_ops::Error>(())
/// ```
#[macro_export]
macro_rules! props {
    () => {{
        let empty: [($crate::props::Key<'static>, $crate::props::PropValue<'static>); 0] = [];
        empty
    }};
    ($($key:expr => $value:expr),+ $(,)?) => {
        [$(($crate::props::Key::from($key), $crate::props::PropValue::from($value))),+]
    };
}

/// A string that borrows from the input when the deserializer lends it.
pub(super) struct Text<'de>(pub(super) Cow<'de, str>);

impl<'de> Deserialize<'de> for Text<'de> {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        deserializer.deserialize_str(TextVisitor).map(Text)
    }
}

struct TextVisitor;

impl<'de> Visitor<'de> for TextVisitor {
    type Value = Cow<'de, str>;

    fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("a string")
    }

    fn visit_borrowed_str<E: de::Error>(
        self,
        text: &'de str,
    ) -> std::result::Result<Self::Value, E> {
        Ok(Cow::Borrowed(text))
    }

    fn visit_str<E: de::Error>(self, text: &str) -> std::result::Result<Self::Value, E> {
        Ok(Cow::Owned(text.to_owned()))
    }

    fn visit_string<E: de::Error>(self, text: String) -> std::result::Result<Self::Value, E> {
        Ok(Cow::Owned(text))
    }
}

/// A JSON property value: a string, number, boolean or `null`, as
/// OfficeCLI's batch `props` object takes them.
impl<'de> Deserialize<'de> for PropValue<'de> {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        deserializer.deserialize_any(ValueVisitor)
    }
}

struct ValueVisitor;

impl<'de> Visitor<'de> for ValueVisitor {
    type Value = PropValue<'de>;

    fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("a property value: a string, number, boolean, array of strings or null")
    }

    /// An array of strings: a [`PropValue::List`] (the metadata keywords,
    /// record 0354).
    fn visit_seq<A: SeqAccess<'de>>(
        self,
        mut seq: A,
    ) -> std::result::Result<Self::Value, A::Error> {
        let mut items = Vec::with_capacity(seq.size_hint().unwrap_or(0).min(64));
        while let Some(Text(item)) = seq.next_element::<Text<'de>>()? {
            items.push(item.into_owned());
        }
        Ok(PropValue::List(Cow::Owned(items)))
    }

    fn visit_bool<E: de::Error>(self, value: bool) -> std::result::Result<Self::Value, E> {
        Ok(PropValue::Bool(value))
    }

    fn visit_i64<E: de::Error>(self, value: i64) -> std::result::Result<Self::Value, E> {
        Ok(PropValue::Int(value))
    }

    fn visit_u64<E: de::Error>(self, value: u64) -> std::result::Result<Self::Value, E> {
        // Keep the integer exact; the registry performs any explicit target
        // coercion later.
        Ok(match i64::try_from(value) {
            Ok(value) => PropValue::Int(value),
            Err(_) => PropValue::Unsigned(value),
        })
    }

    fn visit_i128<E: de::Error>(self, value: i128) -> std::result::Result<Self::Value, E> {
        Ok(match i64::try_from(value) {
            Ok(value) => PropValue::Int(value),
            Err(_) => PropValue::WideInt(value),
        })
    }

    fn visit_u128<E: de::Error>(self, value: u128) -> std::result::Result<Self::Value, E> {
        Ok(match i64::try_from(value) {
            Ok(value) => PropValue::Int(value),
            Err(_) => match u64::try_from(value) {
                Ok(value) => PropValue::Unsigned(value),
                Err(_) => PropValue::WideUnsigned(value),
            },
        })
    }

    fn visit_f64<E: de::Error>(self, value: f64) -> std::result::Result<Self::Value, E> {
        Ok(PropValue::Number(value))
    }

    fn visit_borrowed_str<E: de::Error>(
        self,
        text: &'de str,
    ) -> std::result::Result<Self::Value, E> {
        Ok(PropValue::Text(Cow::Borrowed(text)))
    }

    fn visit_str<E: de::Error>(self, text: &str) -> std::result::Result<Self::Value, E> {
        Ok(PropValue::Text(Cow::Owned(text.to_owned())))
    }

    fn visit_string<E: de::Error>(self, text: String) -> std::result::Result<Self::Value, E> {
        Ok(PropValue::Text(Cow::Owned(text)))
    }

    fn visit_unit<E: de::Error>(self) -> std::result::Result<Self::Value, E> {
        Ok(PropValue::Null)
    }

    fn visit_none<E: de::Error>(self) -> std::result::Result<Self::Value, E> {
        Ok(PropValue::Null)
    }
}

/// Writes JSON's natural types: `null`, booleans, numbers, and strings for
/// text, lengths and colours (their canonical text). Integers wider than
/// 64 bits use decimal strings so JSON readers cannot round them through
/// floating point. Non-finite numbers are rejected.
impl Serialize for PropValue<'_> {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        match self {
            Self::Null => serializer.serialize_unit(),
            Self::Bool(value) => serializer.serialize_bool(*value),
            Self::Int(value) => serializer.serialize_i64(*value),
            Self::Unsigned(value) => serializer.serialize_u64(*value),
            Self::WideInt(_) | Self::WideUnsigned(_) => serializer.collect_str(self),
            Self::Number(value) if !value.is_finite() => {
                Err(serde::ser::Error::custom("property numbers must be finite"))
            },
            Self::Number(value) => serializer.serialize_f64(*value),
            Self::Text(text) => serializer.serialize_str(text),
            Self::Length(_) | Self::Color(_) => serializer.collect_str(self),
            Self::List(items) => serializer.collect_seq(items.iter()),
        }
    }
}

/// OfficeCLI's batch `props`: an object of `key: value`, or an array of
/// `"key=value"` strings (split at the first `=`, keys and values borrowed
/// from the input where it lends them). A `null` value is
/// [`PropValue::Null`] and an array of strings a [`PropValue::List`]; an
/// empty key, an array entry without `=`, and a value that is an object or
/// an array holding anything but strings are refused (OfficeCLI skips the
/// first two silently).
impl<'de> Deserialize<'de> for Props<'de> {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        deserializer.deserialize_any(PropsVisitor)
    }
}

struct PropsVisitor;

impl<'de> Visitor<'de> for PropsVisitor {
    type Value = Props<'de>;

    fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("an object of properties or an array of \"key=value\" strings")
    }

    fn visit_map<A: MapAccess<'de>>(
        self,
        mut map: A,
    ) -> std::result::Result<Self::Value, A::Error> {
        let mut props = Props::with_capacity(map.size_hint().unwrap_or(0).min(64));
        while let Some(Text(key)) = map.next_key::<Text<'de>>()? {
            if key.is_empty() {
                return Err(de::Error::custom("a property key is empty"));
            }
            let value = map.next_value::<PropValue<'de>>()?;
            props.pairs.push((Key::from(key), value));
        }
        Ok(props)
    }

    fn visit_seq<A: SeqAccess<'de>>(
        self,
        mut seq: A,
    ) -> std::result::Result<Self::Value, A::Error> {
        let mut props = Props::with_capacity(seq.size_hint().unwrap_or(0).min(64));
        while let Some(Text(entry)) = seq.next_element::<Text<'de>>()? {
            let pair = match entry {
                Cow::Borrowed(entry) => split_entry(entry)
                    .map(|(key, value)| (Key::new(key), PropValue::Text(Cow::Borrowed(value)))),
                Cow::Owned(mut entry) => entry.find('=').filter(|at| *at > 0).map(|at| {
                    let value = entry.split_off(at + 1);
                    entry.truncate(at);
                    (Key::from(entry), PropValue::Text(Cow::Owned(value)))
                }),
            };
            match pair {
                Some(pair) => props.pairs.push(pair),
                None => {
                    return Err(de::Error::custom(
                        "a props array entry is not a \"key=value\" string with a non-empty key",
                    ));
                },
            }
        }
        Ok(props)
    }
}

/// Writes OfficeCLI's object form.
impl Serialize for Props<'_> {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        let mut map = serializer.serialize_map(Some(self.pairs.len()))?;
        for (key, value) in &self.pairs {
            map.serialize_entry(key.as_str(), value)?;
        }
        map.end()
    }
}

