#[cfg(test)]
mod tests {
    use super::{is_combining, is_digit, is_letter};

    #[test]
    fn letter_uses_xml_base_and_ideographic_boundaries() {
        for character in [
            'A', 'Z', 'a', 'z', '\u{00C0}', '\u{00D6}', '\u{0386}', '\u{0559}', '\u{1FF4}',
            '\u{1FF6}', '\u{3007}', '\u{3021}', '\u{3029}', '\u{4E00}', '\u{9FA5}', '\u{AC00}',
            '\u{D7A3}',
        ] {
            assert!(
                is_letter(character),
                "XML Letter should contain U+{:04X}",
                character as u32
            );
        }

        for character in [
            '@',
            '[',
            '\u{00D7}',
            '\u{00F7}',
            '\u{0387}',
            '\u{0557}',
            '\u{1FF5}',
            '\u{3006}',
            '\u{302A}',
            '\u{3095}',
            '\u{9FA6}',
            '\u{D7A4}',
            '\u{10000}',
            '\u{1D400}',
        ] {
            assert!(
                !is_letter(character),
                "XML Letter should exclude U+{:04X}",
                character as u32
            );
        }
    }

    #[test]
    fn digit_is_the_xml_digit_table_not_unicode_numeric() {
        for character in [
            '0', '9', '\u{0660}', '\u{0669}', '\u{06F0}', '\u{06F9}', '\u{0966}', '\u{096F}',
            '\u{0F20}', '\u{0F29}',
        ] {
            assert!(
                is_digit(character),
                "XML Digit should contain U+{:04X}",
                character as u32
            );
        }

        for character in [
            '/',
            ':',
            '\u{065F}',
            '\u{066A}',
            '\u{0BE6}',
            '\u{0BF0}',
            '\u{1D7CE}',
            '\u{10000}',
        ] {
            assert!(
                !is_digit(character),
                "XML Digit should exclude U+{:04X}",
                character as u32
            );
        }
    }

    #[test]
    fn combining_character_boundaries_and_excluded_marks_are_exact() {
        for character in [
            '\u{0300}', '\u{0345}', '\u{0360}', '\u{05BF}', '\u{0901}', '\u{0A3E}', '\u{0FAD}',
            '\u{20D0}', '\u{20E1}', '\u{302A}', '\u{3099}', '\u{309A}',
        ] {
            assert!(
                is_combining(character),
                "XML CombiningChar should contain U+{:04X}",
                character as u32
            );
        }

        for character in [
            '\u{02FF}', '\u{0346}', '\u{0482}', '\u{05A2}', '\u{05BE}', '\u{05C3}', '\u{093D}',
            '\u{0A3D}', '\u{20DD}', '\u{3029}', '\u{309B}', '\u{1AB0}',
        ] {
            assert!(
                !is_combining(character),
                "XML CombiningChar should exclude U+{:04X}",
                character as u32
            );
        }
    }

    #[test]
    fn ranges_are_character_based_and_do_not_accept_broad_unicode_classes() {
        assert!(is_letter('\u{4E00}'));
        assert!(!is_letter('\u{20000}'));
        assert!(!is_digit('\u{1D7D8}'));
        assert!(!is_combining('\u{1D165}'));
    }
}
