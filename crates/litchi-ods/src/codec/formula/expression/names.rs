//! XML 1.0 character classes used by the OpenFormula name grammar.
//!
//! OpenFormula 1.4 §5.6 and §5.11 call these classes `LetterXML`, `DigitXML`,
//! and `CombiningCharXML`, and explicitly define them through XML 1.0.  These
//! tables intentionally retain XML 1.0's finite historical character classes;
//! Rust's Unicode predicates and XML `NameStartChar` are broader grammars.

// ODF 1.4 Part 4's [XML1.0] bibliography names XML 1.0 Fourth Edition:
// <https://www.w3.org/TR/2006/REC-xml-20060816/>.
// The exact source productions are XML 1.0 Appendix B, [84] Letter,
// [85] BaseChar, [86] Ideographic, [87] CombiningChar, and [88] Digit.
// LetterXML is the Part 4 spelling of XML's Letter production.  The fifth
// edition keeps these Appendix-B tables; its broader NameStartChar production
// is deliberately not used here.

/// XML 1.0 `Letter` = `BaseChar | Ideographic`, productions [84]-[86].
pub(super) fn is_letter(character: char) -> bool {
    contains(LETTER_RANGES, character as u32)
}

/// XML 1.0 `Digit`, production [88].
pub(super) fn is_digit(character: char) -> bool {
    contains(DIGIT_RANGES, character as u32)
}

/// XML 1.0 `CombiningChar`, production [87].
pub(super) fn is_combining(character: char) -> bool {
    contains(COMBINING_RANGES, character as u32)
}

fn contains(ranges: &[(u32, u32)], value: u32) -> bool {
    let mut low = 0;
    let mut high = ranges.len();
    while low < high {
        let middle = low + (high - low) / 2;
        let (start, end) = ranges[middle];
        if value < start {
            high = middle;
        } else if value > end {
            low = middle + 1;
        } else {
            return true;
        }
    }
    false
}

