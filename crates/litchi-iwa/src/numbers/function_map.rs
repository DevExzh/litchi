pub(crate) fn function_name(identifier: u32) -> Option<&'static str> {
    FORMULA_FUNCTIONS.get(&identifier).copied()
}

pub(crate) fn function_identifier(name: &str) -> Option<u32> {
    FORMULA_FUNCTIONS
        .entries()
        .find_map(|(identifier, candidate)| {
            candidate.eq_ignore_ascii_case(name).then_some(*identifier)
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolves_observed_function_tokens_both_ways() {
        assert_eq!(function_name(168), Some("SUM"));
        assert_eq!(function_name(62), Some("IF"));
        assert_eq!(function_identifier("sum"), Some(168));
        assert_eq!(function_identifier("XLOOKUP"), Some(314));
        assert_eq!(function_name(999), None);
    }
}
